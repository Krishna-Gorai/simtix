"""
gen_vxbin.py - turn a Vortex kernel image (.vxbin) into vx_image.h for the A53 host.

    python gen_vxbin.py path/to/kernel.vxbin

.vxbin (Vortex sw/kernel/scripts/vxbin.py): min_vma (8 bytes LE), max_vma (8 bytes),
the binary, and a VXSYMTAB footer (name blob, entries {name_off:4, name_len:2, pad:2,
pc:8}, n_symbols:4, 'VXSYMTAB'). The header gives the image as words from min_vma
up to max_vma (the .bss zero-filled) and the PC of the kernel 'main'.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
path = sys.argv[1]
b = open(path, 'rb').read()
min_vma, max_vma = struct.unpack_from('<QQ', b, 0)
footer, main_pc = 0, min_vma
if b[-8:] == b'VXSYMTAB':
    n = struct.unpack_from('<I', b, len(b) - 12)[0]
    ents = [struct.unpack_from('<IHHQ', b, len(b) - 12 - 16 * n + 16 * i) for i in range(n)]
    blob_len = max(off + ln for off, ln, _, _ in ents) if ents else 0
    footer = 12 + 16 * n + blob_len
    blob = b[len(b) - footer:len(b) - footer + blob_len]
    for off, ln, _, pc in ents:
        if blob[off:off + ln] == b'main':
            main_pc = pc
binary = b[16:len(b) - footer]
image = binary + b'\0' * (max_vma - min_vma - len(binary))
image += b'\0' * (-len(image) % 4)
words = [int.from_bytes(image[i:i + 4], 'little') for i in range(0, len(image), 4)]
out = ['/* vx_image.h - generated by gen_vxbin.py from %s; do not edit */' % os.path.basename(path),
       '#include <stdint.h>',
       '#define VX_IMG_BASE 0x%08xu   /* Vortex address of the image (KMU startup) */' % min_vma,
       '#define VX_MAIN_PC  0x%08xu   /* kernel entry: main */' % main_pc,
       'static const uint32_t vx_image[%d] = {' % len(words)]
for i in range(0, len(words), 8):
    out.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
out += ['};', '']
open(os.path.join(HERE, 'vx_image.h'), 'w').write('\n'.join(out))
print('%s: image 0x%08x-0x%08x (%d words), main at 0x%08x' % (path, min_vma, max_vma, len(words), main_pc))
