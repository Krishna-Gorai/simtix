#!/usr/bin/env python3
"""gen_fgpu_image.py - FGPU kernel images for the A53 host (fgpu_image.h).

FGPU's compiler (kernels/compile.sh, LLVM 3.7.1 with FGPU's backend, built by
baselines/fgpu/build_fgpu_llvm.sh) writes <name>.c (the code words) and <name>.h (the length and
each kernel's entry word). This collects them into one header:
    static const uint32_t fgpu_code_<name>[] = {...};
    #define FG_<NAME>_LEN ...  and FG_<NAME>_<KERNEL>_POS for the entries of <name>.h
    python baselines/fgpu/host/gen_fgpu_image.py [dir] vec_add vec_add_hard_float ...
dir defaults to C:/work/fgpu_build/kernels (the compiled outputs, copied out of WSL).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
args = sys.argv[1:]
src = args.pop(0) if args and os.path.isdir(args[0]) else 'C:/work/fgpu_build/kernels'
names = args or ['vec_add', 'vec_add_hard_float']
out = ['/* fgpu_image.h - generated by gen_fgpu_image.py from FGPU compiler outputs; do not edit */',
       '#include <stdint.h>']
for n in names:
    words = re.findall(r'0x([0-9a-fA-F]{8})', open(os.path.join(src, f'{n}.c')).read())
    out.append(f'static const uint32_t fgpu_code_{n}[{len(words)}] = {{')
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join(f'0x{w.lower()}u' for w in words[i:i + 8]) + ',')
    out.append('};')
    # names prefixed with the image (two suites both have a pathfinder):
    # <STEM>_LEN -> FG_<STEM>_LEN, <KERNEL>_POS -> FG_<STEM>_<KERNEL>_POS
    for line in open(os.path.join(src, f'{n}.h')):
        m = re.match(r'#define\s+(\w+)\s+(\d+)', line)
        if m:
            name = m.group(1)
            name = f'FG_{name}' if name == f'{n.upper()}_LEN' else f'FG_{n.upper()}_{name}'
            out.append(f'#define {name} {m.group(2)}u')
    print(f'{n}: {len(words)} words')
path = os.path.join(HERE, 'fgpu_image.h')
open(path, 'w', newline='\n').write('\n'.join(out) + '\n')
print('written', path)
