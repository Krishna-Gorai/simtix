"""
gen_progs.py - turn Ara programs (RV64 ELFs linked at 0x8000_0000) into ara_progs.h
for the A53 host.

    python gen_progs.py name=path/to/prog.elf [name=...]

Each ELF becomes a flat image from 0x8000_0000 (objcopy -O binary) with .bss and
.sbss included as zeros: Ara's crt0 does not clear them, and DDR holds old data.
"""
import os
import subprocess
import sys
import tempfile

OBJCOPY = r'C:\toolchains\xpack-riscv-none-elf-gcc-15.2.0-1\bin\riscv-none-elf-objcopy.exe'
HERE = os.path.dirname(os.path.abspath(__file__))

progs = [a.split('=', 1) for a in sys.argv[1:]]
out = ['/* ara_progs.h - generated by gen_progs.py; do not edit */',
       '#include <stdint.h>', '']
table = []
for name, elf in progs:
    with tempfile.TemporaryDirectory() as td:
        binf = os.path.join(td, 'p.bin')
        subprocess.run([OBJCOPY, '-O', 'binary',
                        '--set-section-flags', '.bss=alloc,load,contents',
                        '--set-section-flags', '.sbss=alloc,load,contents',
                        elf, binf], check=True)
        data = open(binf, 'rb').read()
    data += b'\0' * (-len(data) % 4)
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    out.append(f'static const uint32_t prog_{name}[{len(words)}] = {{')
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
    out.append('};')
    table.append(f'    {{ "{name}", prog_{name}, {len(words)}u }},')
    print(f'{name}: {elf}, {len(data)} bytes')
out += ['', 'struct ara_prog { const char *name; const uint32_t *img; uint32_t words; };',
        'static const struct ara_prog ara_progs[] = {'] + table + ['};', '']
open(os.path.join(HERE, 'ara_progs.h'), 'w').write('\n'.join(out))
