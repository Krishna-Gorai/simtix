#!/usr/bin/env python3
"""gen_div_fig.py - divergence and reconvergence of one warp, from the RTL trace.

Reads traces/div_fig.txt (fig_trace.py: kernels/figs/divergence.S on one eight-lane warp,
board configuration) and draws, for every issue slot the warp takes until it has
reconverged, its active lanes (filled) coloured by the depth of the frame that runs them,
the pops, and the reconvergence stack after the if's push and at the loop's deepest point.
Every value comes from the trace: X lines give the slot, its mask and pop/issue, F lines
the stack, B lines the branch outcomes.
Writes simtix_div.tex; build with pdflatex.  Usage: python gen_div_fig.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(HERE, "simtix_div.tex")
TRACE = os.path.join(HERE, "traces", "div_fig.txt")
SRC = os.path.join(ROOT, "kernels", "figs", "divergence.S")
BASE_PC = 0x100                                  # tb_figtrace places the kernel at word 64
DEPTH_FILL = ["dA", "dB", "dC", "dD"]            # frame depth 0..3 (viridis steps)

PRE = r"""% generated by gen_div_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,patterns,decorations.pathreplacing}
\definecolor{dA}{HTML}{481D6F}
\definecolor{dB}{HTML}{2E6F8E}
\definecolor{dC}{HTML}{2CB17E}
\definecolor{dD}{HTML}{CAE11F}
\definecolor{cpop}{HTML}{C55A11}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.8}{6.6}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  tbl/.style={draw=black!70, line width=0.3pt},
  lbl/.style={font=\fs, inner sep=0.5pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left},
  code/.style={font=\fss\ttfamily, inner sep=0.5pt, anchor=west},
  panel/.style={draw=black!40, dashed, rounded corners=3pt, fill=black!1, line width=0.5pt},
  subcap/.style={font=\fs, inner sep=1pt},
  arr/.style={-{Latex[length=1.2mm, width=0.9mm]}, line width=0.5pt}]
"""


def f(x):
    return "%.3f" % x


def mask_lanes(m):
    """'11111000' (lane 7 first, as $fdisplay %b prints it) -> set of lanes."""
    return {7 - i for i, c in enumerate(m) if c == '1'}


def program():
    ins = []
    for line in open(SRC):
        s = line.split('#')[0].strip()
        s = re.sub(r'^\d+:\s*', '', s)
        if s and not s.startswith('.') and not s.endswith(':'):
            ins.append(re.sub(r'\s+', ' ', s, count=1))
    return {BASE_PC + 4 * i: s for i, s in enumerate(ins)}


def parse():
    fetch, slots, branches = {}, [], {}
    for line in open(TRACE):
        p = line.split()
        if not p or p[0] not in ('F', 'X', 'B'):
            continue
        c = int(p[1])
        if p[0] == 'F':
            sp = int(p[4])
            frames = [(int(p[5 + 3 * i], 16), int(p[6 + 3 * i], 16), mask_lanes(p[7 + 3 * i]))
                      for i in range(sp + 1)]
            fetch[c] = (int(p[3], 16), sp, frames)
        elif p[0] == 'X':
            slots.append(dict(cyc=c, pc=int(p[3], 16), lanes=mask_lanes(p[4]), kind=p[5]))
        else:
            branches[c] = (p[3], mask_lanes(p[4]))
    for s in slots:                              # the fetch one cycle before gives the stack
        s['sp'], s['frames'] = fetch[s['cyc'] - 1][1], fetch[s['cyc'] - 1][2]
        s['br'] = branches.get(s['cyc'] + 1)
    # keep the slots up to the first full-warp issue after the last pop
    last_pop = max(i for i, s in enumerate(slots) if s['kind'] == 'pop')
    return slots[:last_pop + 2], fetch


def stack_table(o, x, ytop, frames, title, pcs):
    """frames: bottom first. Draws TOS on top: PC | RPC | mask squares."""
    cw = [0.62, 0.62, 8 * 0.17]
    rh = 0.25
    o.append(r"\node[note, anchor=south west] at (%s,%s) {%s};" % (f(x), f(ytop + 0.02), title))
    heads = ["PC", "RPC", "lanes 0\\,--\\,7"]
    xs = [x, x + cw[0], x + cw[0] + cw[1], x + sum(cw)]
    y = ytop
    for j, h in enumerate(heads):
        o.append(r"\draw[tbl, fill=black!6] (%s,%s) rectangle (%s,%s);" % (f(xs[j]), f(y - rh), f(xs[j + 1]), f(y)))
        o.append(r"\node[note] at (%s,%s) {%s};" % (f((xs[j] + xs[j + 1]) / 2), f(y - rh / 2), h))
    for d in range(len(frames) - 1, -1, -1):
        y -= rh
        pc, rpc, lanes = frames[d]
        cells = ["0x%x" % pc, "--" if rpc == 0xffffffff else "0x%x" % rpc]
        for j in range(2):
            o.append(r"\draw[tbl] (%s,%s) rectangle (%s,%s);" % (f(xs[j]), f(y - rh), f(xs[j + 1]), f(y)))
            o.append(r"\node[note, font=\fss\ttfamily] at (%s,%s) {%s};"
                     % (f((xs[j] + xs[j + 1]) / 2), f(y - rh / 2), cells[j]))
        for l in range(8):
            xa = xs[2] + l * 0.17
            fill = DEPTH_FILL[d] if l in lanes else "white"
            o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (fill, f(xa), f(y - rh), f(xa + 0.17), f(y)))
        o.append(r"\node[note, anchor=west] at (%s,%s) {%s};"
                 % (f(xs[3] + 0.05), f(y - rh / 2), "top" if d == len(frames) - 1 else ""))


def main():
    slots, fetch = parse()
    pcs = program()
    o = [PRE]
    # ── (a) the kernel ───────────────────────────────────────────────────────────
    ax0, ax1, y0, y1 = -0.10, 4.40, -0.05, 5.65
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(ax0), f(y0), f(ax1), f(y1)))
    lh = 0.305
    ytop = 5.25
    order = sorted(pcs)
    for i, pc in enumerate(order):
        y = ytop - i * lh
        o.append(r"\node[code, text=black!55] at (0.05,%s) {%x};" % (f(y), pc))
        op, _, args = pcs[pc].partition(' ')
        o.append(r"\node[code] at (0.55,%s) {%s};" % (f(y), op))
        o.append(r"\node[code] at (1.25,%s) {%s};" % (f(y), args.replace('_', r'\_')))
    def brace(pa, pb, text):
        ia, ib = order.index(pa), order.index(pb)
        ya, yb = ytop - ia * lh + 0.12, ytop - ib * lh - 0.12
        o.append(r"\draw[decorate, decoration={brace, amplitude=2.5pt}, line width=0.4pt] (2.62,%s) -- (2.62,%s);"
                 % (f(ya), f(yb)))
        o.append(r"\node[note, anchor=west] at (2.74,%s) {%s};" % (f((ya + yb) / 2), text))
    brace(0x108, 0x10c, r"if (tid $\geq$ 3)")
    brace(0x114, 0x11c, r"loop: lane $l$\\runs it\\$(l \bmod 4)+1$\\times")
    # the same kernel in C, below the listing
    csrc = [r"x = 0;", r"if (tid >= 3)", r"\ \ x = 2 * tid + 1;",
            r"for (i = tid \% 4; i >= 0; i--)", r"\ \ x += 1;", r"C[tid] = x;"]
    yc = ytop - len(order) * lh - 0.18
    o.append(r"\node[note, anchor=west, text=black!60] at (0.05,%s) {in C:};" % f(yc))
    for i, t in enumerate(csrc):
        o.append(r"\node[code] at (0.62,%s) {%s};" % (f(yc - i * 0.26), t))
    o.append(r"\node[subcap] at (%s,%s) {(a) Kernel};" % (f((ax0 + ax1) / 2), f(y0 - 0.30)))

    # ── (b) the warp, slot by slot ───────────────────────────────────────────────
    bx0, bx1 = 4.55, 18.15
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(bx0), f(y0), f(bx1), f(y1)))
    gx, cw, ch = 5.45, 0.545, 0.25
    gtop = 4.98                                   # upper edge of lane 0's row
    for l in range(8):
        o.append(r"\node[lbl, anchor=east] at (%s,%s) {lane %d};" % (f(gx - 0.06), f(gtop - (l + 0.5) * ch), l))
    for j, s in enumerate(slots):
        xa = gx + j * cw
        for l in range(8):
            ya = gtop - (l + 1) * ch
            if l in s['lanes']:
                if s['kind'] == 'pop':
                    style = "tbl, pattern=north east lines, pattern color=cpop"
                else:
                    style = "tbl, fill=%s" % DEPTH_FILL[s['sp']]
            else:
                style = "tbl, fill=white"
            o.append(r"\draw[%s] (%s,%s) rectangle (%s,%s);" % (style, f(xa), f(ya), f(xa + cw), f(ya + ch)))
        name = "pop" if s['kind'] == 'pop' else pcs[s['pc']].split()[0]
        col = "cpop" if s['kind'] == 'pop' else "black"
        o.append(r"\node[lbl, text=%s, rotate=90, anchor=west] at (%s,%s) {%s};"
                 % (col, f(xa + cw / 2), f(gtop + 0.05), name))
        o.append(r"\node[note] at (%s,%s) {%d};" % (f(xa + cw / 2), f(gtop - 8 * ch - 0.14), s['cyc']))
        o.append(r"\node[note] at (%s,%s) {%d};" % (f(xa + cw / 2), f(gtop - 8 * ch - 0.40), s['sp'] + 1))
        if s['br'] and s['br'][0] == 'diverge':      # this branch pushes a frame at stage B
            o.append(r"\draw[arr, draw=black!70] (%s,%s) -- (%s,%s);"
                     % (f(xa + cw), f(gtop - 8 * ch - 0.64), f(xa + 1.3 * cw), f(gtop - 8 * ch - 0.64)))
            o.append(r"\node[note, text=black!70] at (%s,%s) {push};" % (f(xa + 0.55 * cw), f(gtop - 8 * ch - 0.64)))
    gend = gx + len(slots) * cw
    o.append(r"\node[note, anchor=east] at (%s,%s) {cycle};" % (f(gx - 0.06), f(gtop - 8 * ch - 0.14)))
    o.append(r"\node[note, anchor=east] at (%s,%s) {frames};" % (f(gx - 0.06), f(gtop - 8 * ch - 0.40)))
    o.append(r"\node[lbl, anchor=west] at (%s,%s) {issue slot};" % (f(gx - 0.95), f(gtop + 0.45)))
    # legend
    ly = y0 + 0.22
    lx = gx
    for d in range(4):
        o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (DEPTH_FILL[d], f(lx), f(ly - 0.08), f(lx + 0.22), f(ly + 0.08)))
        o.append(r"\node[note, anchor=west] at (%s,%s) {%d};" % (f(lx + 0.25), f(ly), d + 1))
        lx += 0.48
    o.append(r"\node[note, anchor=west] at (%s,%s) {active lane, by frames on the stack};" % (f(lx), f(ly)))
    lx += 3.40
    o.append(r"\draw[tbl, pattern=north east lines, pattern color=cpop] (%s,%s) rectangle (%s,%s);" % (f(lx), f(ly - 0.08), f(lx + 0.22), f(ly + 0.08)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {a frame pops at its RPC (takes the slot)};" % (f(lx + 0.27), f(ly)))
    lx += 4.45
    o.append(r"\draw[tbl, fill=white] (%s,%s) rectangle (%s,%s);" % (f(lx), f(ly - 0.08), f(lx + 0.22), f(ly + 0.08)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {masked};" % (f(lx + 0.27), f(ly)))
    # stack snapshots: after the if's push, and at the deepest point of the loop
    first_push = next(j for j, s in enumerate(slots) if s['br'] and s['br'][0] == 'diverge')
    deepest = max(range(len(slots)), key=lambda j: (slots[j]['sp'], -j))
    for j, what in ((first_push + 1, "after the if's push"), (deepest, "at the loop's deepest point")):
        s = slots[j]
        xt = gx + j * cw - 0.30 if j < len(slots) // 2 else gend - 2.95
        o.append(r"\draw[tbl, draw=black, line width=0.6pt] (%s,%s) rectangle (%s,%s);"
                 % (f(gx + j * cw), f(gtop - 8 * ch), f(gx + (j + 1) * cw), f(gtop)))
        o.append(r"\draw[line width=0.4pt, densely dotted] (%s,%s) -- (%s,%s);"
                 % (f(gx + (j + 0.5) * cw), f(gtop - 8 * ch - 0.52), f(gx + (j + 0.5) * cw), f(1.98)))
        stack_table(o, xt, 1.92, s['frames'], "stack at cycle %d, %s" % (s['cyc'] - 1, what), pcs)
    o.append(r"\node[subcap] at (%s,%s) {(b) One warp, issue slot by issue slot, and its reconvergence stack};"
             % (f((bx0 + bx1) / 2), f(y0 - 0.30)))
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT, "slots", len(slots))


if __name__ == "__main__":
    main()
