#!/usr/bin/env python3
"""gen_wave_col_fig.py - three one-column waveform windows of the SAXPY launch (the paper's
Figs. 3 to 5), each with the signals that matter in it and dashed callouts that say what the
values mean, in the style of annotated logic-analyser captures.

  a: cycles 8-23   the loads of a: one L1 miss, seven joins, one AXI4 read
  b: cycles 54-69  the loads of x and y leave every other cycle; the FMAs are held back and the
                   warps fall asleep
  c: cycles 96-111 the lines of y return; warp 0 wakes, issues its FMA and its store, and is
                   parked
Every value is read from the RTL trace (launch_trace.py, traces/saxpy92_*).
Writes simtix_wave_{a,b,c}.tex; build with pdflatex.  Usage: python gen_wave_col_fig.py
"""
import os

from launch_trace import NSLOT, WINDOWS, Launch, line_name
from wavetikz import Axis, bus, clock, f, label

HERE = os.path.dirname(os.path.abspath(__file__))
X0, PITCH, H = 1.05, 0.300, 0.205

PRE = r"""% generated by gen_wave_col_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath}
\usepackage{tikz}
\usetikzlibrary{patterns,arrows.meta}
\definecolor{csleep}{HTML}{D9D9D9}
\definecolor{cpark}{HTML}{F8CBAD}
\definecolor{cread}{HTML}{DDEBF7}
\definecolor{cwrite}{HTML}{FCE4D6}
\definecolor{cmiss}{HTML}{F4B6B6}
\definecolor{cjoin}{HTML}{FFE699}
\definecolor{cld}{HTML}{C6E0B4}
\definecolor{cfpu}{HTML}{FFE699}
\definecolor{ccall}{HTML}{C00000}
\newcommand{\fss}{\fontsize{5.6}{6.4}\selectfont}
\newcommand{\fv}{\fontsize{5.0}{5.6}\selectfont}
\newcommand{\fvs}{\fontsize{4.5}{5.0}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  wire/.style={draw=black, line width=0.4pt, line join=round},
  gridline/.style={draw=black!12, line width=0.25pt},
  call/.style={draw=ccall, line width=0.5pt, dashed, -{Latex[length=1.2mm, width=0.9mm]}},
  callt/.style={font=\fss\itshape, text=ccall, inner sep=0.8pt, align=left}]
"""
HELD = "fill=white, pattern=north east lines, pattern color=black!45"


def build(T, c0, c1, rows, callouts, out):
    cw = (8.70 - X0) / (c1 - c0 + 1)
    ax = Axis(X0, c0, c1, cw)
    cyc = range(c0, c1 + 1)
    o = [PRE]
    ytop = 0.0
    ybot = ytop - 0.30 - len(rows) * PITCH
    for c in cyc:
        o.append(r"\node[font=\fv, text=black!60] at (%s,%s) {%d};" % (f(ax.x(c) + cw / 2), f(ytop - 0.12), c))
    for c in range(c0, c1 + 2):
        o.append(r"\draw[gridline] (%s,%s) -- (%s,%s);" % (f(ax.x(c)), f(ytop - 0.24), f(ax.x(c)), f(ybot + 0.03)))
    o.append(r"\node[anchor=east, font=\fv, text=black!60] at (%s,%s) {cycle};" % (f(X0 - 0.10), f(ytop - 0.12)))
    ycen = {}
    y = ytop - 0.30
    for name, kind, vals, fills, text in rows:
        y -= PITCH
        ys = y + (PITCH - H) / 2
        ycen[name] = ys + H / 2
        label(o, ax, ys, H, name.replace("_", r"\_"))
        if kind == "clock":
            clock(o, ax, ys, H)
        elif kind == "slot":
            slot_row(o, ax, ys, T, vals)
        else:
            bus(o, ax, ys, H, [vals(c) for c in cyc], fills=fills, text=text,
                font=r"\fvs" if name == "opcode" else r"\fv", min_w=0.3, split=lambda c: kind == "event")
    # callouts: a note below the waveform; a dashed arrow rises from the note to the near edge
    # of each cell it explains, so that it crosses no value label
    for note, nx, targets in callouts:
        lines = note.split(r"\\")
        wnote = 0.088 * max(len(l) for l in lines)
        o.append(r"\node[callt, anchor=north west] at (%s,%s) {%s};" % (f(nx), f(ybot - 0.10), note))
        for row, c in targets:
            tx = ax.x(c) + 0.035                      # on the slanted edge: no text there
            sx = min(max(tx, nx + 0.10), nx + wnote - 0.10)
            o.append(r"\draw[call] (%s,%s) -- (%s,%s);" % (f(sx), f(ybot - 0.10), f(tx), f(ycen[row] - H / 2 - 0.01)))
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(out, "w").write("\n".join(o) + "\n")
    print("wrote", out)


def slot_row(o, ax, y, T, k):
    from wavetikz import SLOPE
    s = min(SLOPE, ax.cw * 0.2)
    cyc = list(range(ax.c0, ax.c1 + 1))
    warps = [T.warp_in(k, c) if T.state(k, c) else None for c in cyc]
    fill = {"sleep": "csleep", "park": "cpark"}
    for i, c in enumerate(cyc):
        st = T.state(k, c)
        if warps[i] is None or st not in fill:
            continue
        first = i == 0 or warps[i - 1] != warps[i]
        last = i == len(cyc) - 1 or warps[i + 1] != warps[i]
        xa = ax.x(c) + (s if first and c != ax.c0 else 0)
        xb = ax.x(c + 1) - (s if last and c != ax.c1 else 0)
        o.append(r"\fill[%s] (%s,%s) rectangle (%s,%s);" % (fill[st], f(xa), f(y), f(xb), f(y + H)))
    bus(o, ax, y, H, warps, fills=lambda v: "fill=none", text=lambda v: "w%d" % v, font=r"\fv", min_w=0.3)


def main():
    T = Launch()
    W = lambda v: "w%d" % v
    fetch = ("fetch", "event", lambda c: T.fetched(c), None, W)
    issue = ("issue", "event", lambda c: (T.issued(c)[0], T.issued(c)[2]) if T.issued(c) else None,
             lambda v: "fill=white" if v[1] else HELD, lambda v: W(v[0]))
    opcode = ("opcode", "event", lambda c: (T.issued(c)[1], T.issued(c)[2]) if T.issued(c) else None,
              lambda v: "fill=white" if v[1] else HELD, lambda v: v[0])
    l1req = ("l1.req", "event", T.l1_req, lambda v: "fill=cwrite" if v[1] else "fill=cread", lambda v: v[0])
    l1tag = ("l1.tag", "event", T.l1_result,
             lambda v: {"miss": "fill=cmiss", "join": "fill=cjoin", "hit": "fill=cld"}[v], None)
    ar = ("axi.ar", "event", lambda c: line_name(T.ar[c][1]) if c in T.ar else None, lambda v: "fill=cread", None)
    rd = ("axi.r", "event", lambda c: T.r_name.get(c), lambda v: "fill=cread", None)
    rf = ("rf.wr", "event", lambda c: T.rf.get(c), lambda v: "fill=cld" if v[1] == "ld" else "fill=cfpu",
          lambda v: v[0])
    asleep = ("asleep", "bus", lambda c: sum(1 for k in range(NSLOT) if T.state(k, c) == "sleep") or None,
              lambda v: "fill=csleep", lambda v: "%d" % v)
    clk = ("clk", "clock", None, None, None)
    slot0 = ("slot[0]", "slot", 0, None, None)

    (a0, a1, _), (b0, b1, _), (c0, c1, _) = WINDOWS
    build(T, a0, a1, [clk, fetch, issue, opcode, l1req, l1tag, ar],
          [(r"the first load of $a$ misses in the L1\\and leaves as one AXI4 read", 1.05,
            [("l1.tag", 14), ("axi.ar", 15)]),
           (r"the other seven loads of $a$\\join the miss in flight", 5.30, [("l1.tag", 18)])],
          os.path.join(HERE, "simtix_wave_a.tex"))
    build(T, b0, b1, [clk, l1req, l1tag, ar, issue, opcode, asleep],
          [(r"the lines of $x$ and $y$ miss; one\\AXI4 read leaves every other cycle", 1.05,
            [("axi.ar", 57)]),
           (r"each FMA is held back,\\and its warp falls asleep", 4.55, [("opcode", 62), ("asleep", 63)])],
          os.path.join(HERE, "simtix_wave_b.tex"))
    build(T, c0, c1, [clk, fetch, issue, opcode, slot0, rd, rf],
          [(r"$y$ of warp 0\\arrives and is\\written to \texttt{f2}", 1.05, [("axi.r", 97), ("rf.wr", 98)]),
           (r"warp 0 wakes: its FMA\\issues, its store is\\held back", 2.98, [("opcode", 101), ("opcode", 103)]),
           (r"the FMA's result (+7);\\the store issues and\\parks warp 0", 6.45, [("rf.wr", 108), ("slot[0]", 111)])],
          os.path.join(HERE, "simtix_wave_c.tex"))

if __name__ == "__main__":
    main()
