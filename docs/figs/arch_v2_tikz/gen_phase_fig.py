#!/usr/bin/env python3
"""gen_phase_fig.py - the critical path of one SAXPY warp as a phase-level timing diagram, one
column wide (the paper's pipeline figure), in the style of a timing diagram of operation phases.

The nine phases and their latencies come from the RTL trace (phase_model.py, traces/saxpy1_*):
spawn to the load of a, the load of a, wake, the load of y, wake, the FMA, the store's fetch,
the store and its write response, and the end of the launch. The clock is drawn cycle by cycle
in the short phases and compressed (dots) in the memory phases. The timeline wraps: the first
row runs left to right, the second right to left, joined by the dotted arrows on the right.
Rows: clk, busy, the warp's memory operations in flight, and the phase (Opr.).
Writes simtix_phase.tex; build with pdflatex.  Usage: python gen_phase_fig.py
"""
import os

from phase_model import events, phases

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_phase.tex")
RUN, LAM = "saxpy1", 24                    # trace and its memory latency (cycles)
P = 0.270                                  # cm per clock cycle where drawn to scale
NSHOW, GAP = 3, 0.60                       # cycles drawn at each end of a compressed phase
X0 = 1.12                                  # left edge of the timeline rows
ROWS = [(0, 4), (4, 9)]                    # phases of the first and of the second row
PH = [(r"spawn,\\\texttt{bgeu}", "hex", "white"),          # text in the shape, shape, fill
      (r"load of $a$: L1 miss,\\AXI4 read", "round", "cload"),
      (r"wake", "ell", "cwake"),
      (r"load of $y$: L1 miss,\\AXI4 read", "round", "cload"),
      (r"wake", "ell", "cwake"),
      (r"FMA", "ell", "cfpu"),
      (r"fetch", "ell", "cwake"),
      (r"store: AXI4 write,\\write response", "round", "cstore"),
      (r"\texttt{ecall},\\DONE", "hex", "white")]
H, HH = 0.26, 0.60                         # signal height, phase-shape height
SIG = {"clk": -0.52, "busy": -0.92, "mem": -1.32, "opr": -2.22}   # low edge in a row
ROWY = [0.0, -2.66]                        # top of each row

PRE = r"""% generated by gen_phase_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{mathptmx}
\usepackage{tikz}
\usetikzlibrary{arrows.meta}
\definecolor{cval}{HTML}{7030A0}
\definecolor{cload}{HTML}{EEE8AA}
\definecolor{cstore}{HTML}{FAD7B5}
\definecolor{cfpu}{HTML}{B4E7EA}
\definecolor{cwake}{HTML}{DDDDDD}
\newcommand{\fs}{\fontsize{6.6}{7.6}\selectfont}
\newcommand{\fss}{\fontsize{5.7}{6.6}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  sig/.style={font=\fs\bfseries\itshape, anchor=east, inner sep=0.5pt},
  val/.style={font=\fss\itshape, text=cval, inner sep=0.5pt},
  wire/.style={line width=0.75pt, line join=round},
  thin/.style={line width=0.45pt, line join=round, draw=cval},
  lam/.style={font=\fs, inner sep=0.5pt},
  lab/.style={font=\fss, align=center, inner sep=0.5pt},
  dim/.style={{Latex[length=1.1mm, width=0.8mm]}-{Latex[length=1.1mm, width=0.8mm]}, line width=0.4pt, dashed},
  conn/.style={-{Latex[length=1.3mm, width=1mm]}, line width=0.55pt, densely dotted}]
"""


def f(v):
    return "%.3f" % v


class Timeline:
    def __init__(self, t, lat):
        self.t, self.lat = t, lat
        self.comp = [l > 2 * NSHOW + 2 for l in lat]
        w = [2 * NSHOW * P + GAP if c else l * P for c, l in zip(self.comp, lat)]
        wa, wb = (sum(w[a:b]) for a, b in ROWS)
        self.xr = X0 + max(wa, wb)                        # both rows end at the same right edge
        self.geo = []
        x = self.xr - wa
        for k in range(*ROWS[0]):
            self.geo.append((0, x, x + w[k]))
            x += w[k]
        x = self.xr
        for k in range(*ROWS[1]):
            self.geo.append((1, x - w[k], x))
            x -= w[k]
        self.lo = [min(g[1] for g in self.geo if g[0] == r) for r in (0, 1)]

    def phase_of(self, c, r):
        a, b = ROWS[r]
        for k in range(a, b):
            if self.t[k] <= c < self.t[k + 1]:
                return k
        return b - 1                                       # the row's last cycle boundary

    def x(self, c, r):
        """x of the start of cycle c on row r (cycle t[b] of a row's end is its far edge)"""
        k = self.phase_of(c, r)
        _, xs, xe = self.geo[k]
        d, n = c - self.t[k], self.lat[k]
        if not self.comp[k] or d <= NSHOW:
            u = d * P
        elif n - d <= NSHOW:
            u = (xe - xs) - (n - d) * P
        else:
            u = NSHOW * P + (d - NSHOW) / (n - 2 * NSHOW) * GAP
        return xs + u if r == 0 else xe - u

    def span(self, c0, c1, r):
        """sorted x extent of cycles [c0, c1) on row r"""
        a, b = self.x(c0, r), self.x(c1, r)
        return min(a, b), max(a, b)


def hexbus(o, xa, xb, y, h, style, fill="white", s=0.06):
    s = min(s, (xb - xa) / 3)
    o.append(r"\draw[%s, fill=%s] (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- cycle;"
             % (style, fill, f(xa), f(y + h / 2), f(xa + s), f(y + h), f(xb - s), f(y + h), f(xb), f(y + h / 2),
                f(xb - s), f(y), f(xa + s), f(y)))


def main():
    t, lat = phases(RUN)
    iv, fv = events(RUN)
    T = Timeline(t, lat)
    o = [PRE]
    names = [("clk", "clk"), ("busy", "busy"), ("mem", "in flight"), ("opr", "Opr.")]
    for r in (0, 1):
        for key, name in names:
            yy = ROWY[r] + SIG[key] + (HH / 2 if key == "opr" else H / 2)
            o.append(r"\node[sig] at (%s,%s) {%s};" % (f(X0 - 0.10), f(yy), name))
    # clock: every cycle of the to-scale parts, dots in the compressed middle of a phase
    for k, (r, xs, xe) in enumerate(T.geo):
        y = ROWY[r] + SIG["clk"]
        cyc = range(t[k], t[k + 1]) if not T.comp[k] else \
            list(range(t[k], t[k] + NSHOW)) + list(range(t[k + 1] - NSHOW, t[k + 1]))
        for c in cyc:
            xa, _ = T.span(c, c + 1, r) if c + 1 < t[k + 1] or not T.comp[k] else T.span(c, c + 1, r)
            xa = min(T.x(c, r), T.x(c, r) - P) if r == 1 else T.x(c, r)
            o.append(r"\draw[wire] (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s);"
                     % (f(xa), f(y), f(xa), f(y + H), f(xa + P / 2), f(y + H), f(xa + P / 2), f(y), f(xa + P), f(y)))
        if T.comp[k]:
            o.append(r"\node[font=\fs] at (%s,%s) {$\cdot\;\cdot\;\cdot\;\cdot\;\cdot$};"
                     % (f((xs + xe) / 2), f(y + 0.04)))
    xa = T.x(1, 0)                                        # the clock period
    yc = ROWY[0] + SIG["clk"] + H + 0.14
    o.append(r"\draw[dim] (%s,%s) -- (%s,%s);" % (f(xa), f(yc), f(xa + P), f(yc)))
    o.append(r"\node[lam, anchor=west] at (%s,%s) {$T_{\mathit{clk}}=8.67$\,ns};" % (f(xa + P + 0.05), f(yc)))
    # busy: logic-1 from the spawn to DONE
    for r in (0, 1):
        y = ROWY[r] + SIG["busy"]
        hexbus(o, T.lo[r], T.xr, y, H, "thin")
        o.append(r"\node[val] at (%s,%s) {logic-1};" % (f((T.lo[r] + T.xr) / 2), f(y + H / 2)))
    # the warp's memory operations in flight: issue to completion, from the trace
    iss = {int(e[2], 16): int(e[0]) for e in iv['I']}
    fin = {}
    for e in iv['R']:
        fin.setdefault((int(e[2]), int(e[3])), []).append(int(e[0]))
    ops = [("a", iss[0x04], fin[(1, 0)][0]), ("x", iss[0x14], fin[(1, 1)][0]),
           ("y", iss[0x18], fin[(1, 2)][0]), ("store", iss[0x20], t[8])]
    def inflight(c):
        v = [n for n, a, b in ops if a <= c < b]
        return ", ".join(v) if v else None
    for r, (a, b) in enumerate(ROWS):
        y = ROWY[r] + SIG["mem"]
        segs = []
        for c in range(t[a], t[b]):
            v = inflight(c)
            if segs and segs[-1][0] == v:
                segs[-1][2] = c
            else:
                segs.append([v, c, c])
        for v, ca, cb in segs:
            xa, xb = T.span(ca, cb + 1, r)
            if v is None:
                o.append(r"\draw[thin] (%s,%s) -- (%s,%s);" % (f(xa), f(y + H / 2), f(xb), f(y + H / 2)))
            else:
                hexbus(o, xa, xb, y, H, "thin")
                if xb - xa > 0.28:
                    o.append(r"\node[val] at (%s,%s) {%s};" % (f((xa + xb) / 2), f(y + H / 2), v))
    # the phases: shape, latency symbol above, cycles below
    for k, (r, xs, xe) in enumerate(T.geo):
        y = ROWY[r] + SIG["opr"]
        text, shape, fill = PH[k]
        xa, xb = xs + 0.015, xe - 0.015
        if shape == "hex":
            hexbus(o, xa, xb, y, HH, "line width=0.9pt", fill, s=0.12)
        elif shape == "round":
            o.append(r"\draw[line width=0.5pt, densely dashed, fill=%s, rounded corners=4pt] (%s,%s) rectangle (%s,%s);"
                     % (fill, f(xa), f(y), f(xb), f(y + HH)))
        else:
            o.append(r"\draw[line width=0.5pt, fill=%s] (%s,%s) ellipse (%s and %s);"
                     % (fill, f((xa + xb) / 2), f(y + HH / 2), f((xb - xa) / 2), f(HH * 0.40)))
        if text:
            o.append(r"\node[lab] at (%s,%s) {%s};" % (f((xa + xb) / 2), f(y + HH / 2), text))
        o.append(r"\node[lam] at (%s,%s) {$\lambda_%d$};" % (f((xa + xb) / 2), f(y + HH + 0.14), k + 1))
        cnt = (r"$\Lambda{+}8=%d$" % lat[k]) if T.comp[k] else ("%d" % lat[k])
        o.append(r"\node[font=\fss, inner sep=0.5pt] at (%s,%s) {%s};" % (f((xa + xb) / 2), f(y - 0.13), cnt))
    # the wrap: dotted arrows from the end of the first row to the start of the second
    cols = {"clk": "red!75!black", "busy": "cval", "mem": "blue!70!black", "opr": "black"}
    for key in ("clk", "busy", "mem", "opr"):
        ya = ROWY[0] + SIG[key] + (HH / 2 if key == "opr" else H / 2)
        yb = ROWY[1] + SIG[key] + (HH / 2 if key == "opr" else H / 2)
        dx = {"clk": 0.62, "busy": 0.50, "mem": 0.38, "opr": 0.26}[key]
        o.append(r"\draw[conn, draw=%s] (%s,%s) .. controls (%s,%s) and (%s,%s) .. (%s,%s);"
                 % (cols[key], f(T.xr + 0.03), f(ya), f(T.xr + dx), f(ya), f(T.xr + dx), f(yb), f(T.xr + 0.05), f(yb)))
    # the total latency under the second row
    yt = ROWY[1] + SIG["opr"] - 0.40
    o.append(r"\draw[dim] (%s,%s) -- (%s,%s);" % (f(T.lo[1]), f(yt), f(T.xr), f(yt)))
    o.append(r"\node[font=\fss, fill=white, inner sep=1pt] at (%s,%s) {$T=\sum_k\lambda_k=3\Lambda+49=%d$ cycles for $\Lambda=%d$};"
             % (f((T.lo[1] + T.xr) / 2), f(yt), t[-1], LAM))
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT, "phases", lat, "T", t[-1])


if __name__ == "__main__":
    main()
