#!/usr/bin/env python3
"""gen_lat_fig.py - latency tolerance in SIMTiX's issue stage, for the TVLSI paper.

(a) Four warps under the issue rules of rtl/accel/warp_pool.sv (lat_sched.py): one warp
    instruction per cycle, round robin over the runnable warps, a warp at most every other
    cycle, a warp sleeps on a pending source register until its result is written, and a
    load does not stop its warp. FPU latency 6 (FPC_LAT); the load latency is schematic.
(b) IPC after each step, the mechanisms added one at a time (docs/v3_steps.csv, simulation
    of the board top at the board's application inputs, 24-cycle AXI memory model): the
    geometric mean of the IPC (warp instructions per cycle) over eight applications (bar)
    and its range over the applications (whisker). The instruction count is the same in
    every step.
Writes simtix_lat.tex.  Usage: python gen_lat_fig.py
"""
import csv
import math
import os
from collections import defaultdict

from lat_sched import schedule

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_lat.tex")
STEPS_CSV = os.path.join(HERE, "..", "..", "v3_steps.csv")
STEPS = [("v2", ["v2 design (4 warps)"]),
         ("b2s1_pipelined_units", ["+ pipelined units"]),
         ("b2s2_scoreboard", ["+ register scoreboard,", "sleeping warps"]),
         ("b2s3_nonblocking_loads", ["+ non-blocking loads"]),
         ("b3_8warps", ["+ eight warps"]),
         ("b4_w8_l1kb64_mshr16_tags16", ["+ 16 MSHRs, 16 tags,", "64 KiB L1"])]
WCOL = ["wA", "wB", "wC", "wD"]
NCYC = 17
BS = "\\"                                     # one backslash, for TeX line breaks
BR = BS + BS

PRE = r"""% generated by gen_lat_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,patterns}
\definecolor{wA}{HTML}{9FC5E8}
\definecolor{wB}{HTML}{F6B26B}
\definecolor{wC}{HTML}{93C47D}
\definecolor{wD}{HTML}{C27BA0}
\definecolor{bar}{HTML}{2A78D6}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.8}{6.6}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  tbl/.style={draw=black!55, line width=0.35pt},
  panel/.style={draw=black!40, dashed, rounded corners=3pt, fill=black!1, line width=0.5pt},
  lbl/.style={font=\fs, inner sep=0.5pt},
  cell/.style={font=\fss, inner sep=0.3pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left},
  subcap/.style={font=\fs, inner sep=1pt},
  sleep/.style={draw=black!45, pattern=north east lines, pattern color=black!45, line width=0.3pt},
  arr/.style={-{Latex[length=1.3mm, width=0.9mm]}, line width=0.5pt}]
"""


def f(x):
    return "%.3f" % x


def steps_data():
    agg = defaultdict(lambda: [0, 0])
    for r in csv.DictReader(open(STEPS_CSV)):
        a = agg[(r["step"], r["case"])]
        a[0] += int(r["cycles"])
        a[1] += int(r["insns"])
    cases = sorted({c for s, c in agg if s == "v2"})
    g = lambda v: math.exp(sum(map(math.log, v)) / len(v))
    out = []
    for s, lab in STEPS:
        ipc = [agg[(s, c)][1] / agg[(s, c)][0] for c in cases]
        out.append((lab, g(ipc), min(ipc), max(ipc)))
    return out, len(cases)


def panel_a(o):
    iss, st, fl = schedule(NCYC, 4)
    X0, CW, Y0, RH = 1.20, 0.56, 3.55, 0.62          # first cycle x, cell width, issue row y, row pitch
    PX = (-0.10, X0 + NCYC * CW + 0.25)
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(PX[0]), f(-0.05), f(PX[1]), f(4.55)))
    for t in range(NCYC):
        o.append(r"\node[cell, text=black!60] at (%s,%s) {%d};" % (f(X0 + (t + 0.5) * CW), f(Y0 + 0.45), t))
    o.append(r"\node[note, anchor=east, text=black!60] at (%s,%s) {cycle};" % (f(X0 - 0.08), f(Y0 + 0.45)))
    ch = 0.34
    o.append(r"\node[lbl, anchor=east] at (%s,%s) {\textbf{issue}};" % (f(X0 - 0.08), f(Y0)))
    for t in range(NCYC):
        x = X0 + t * CW
        if t in iss:
            w, _ = iss[t]
            o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (WCOL[w], f(x), f(Y0 - ch / 2), f(x + CW), f(Y0 + ch / 2)))
            o.append(r"\node[cell] at (%s,%s) {%d};" % (f(x + CW / 2), f(Y0), w))
        else:
            o.append(r"\draw[tbl, fill=white] (%s,%s) rectangle (%s,%s);" % (f(x), f(Y0 - ch / 2), f(x + CW), f(Y0 + ch / 2)))
            o.append(r"\node[cell, text=red!70!black] at (%s,%s) {--};" % (f(x + CW / 2), f(Y0)))
    for w in range(4):
        y = Y0 - (w + 1) * RH - 0.08
        o.append(r"\node[lbl, anchor=east] at (%s,%s) {warp %d};" % (f(X0 - 0.08), f(y), w))
        o.append(r"\draw[black!25, line width=0.3pt] (%s,%s) -- (%s,%s);" % (f(X0), f(y - 0.27), f(X0 + NCYC * CW), f(y - 0.27)))
        for t in range(NCYC):
            x = X0 + t * CW
            s = st[w].get(t)
            if s == "I":
                o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (WCOL[w], f(x), f(y - 0.03), f(x + CW), f(y + 0.21)))
                o.append(r"\node[cell] at (%s,%s) {\fontsize{4.9}{5.4}\selectfont %s};" % (f(x + CW / 2), f(y + 0.09), iss[t][1]))
            elif s == "S":
                o.append(r"\draw[sleep] (%s,%s) rectangle (%s,%s);" % (f(x + 0.02), f(y), f(x + CW - 0.02), f(y + 0.18)))
        for (a, b, kind) in fl[w]:                     # result in flight, written at b
            if a >= NCYC:
                continue
            yb = y - 0.13
            xe = X0 + min(b, NCYC) * CW
            o.append(r"\draw[line width=0.6pt, draw=%s!75!black] (%s,%s) -- (%s,%s);"
                     % (WCOL[w], f(X0 + (a + 0.5) * CW), f(yb), f(xe), f(yb)))
            if b < NCYC:
                o.append(r"\fill[%s!75!black] (%s,%s) circle (0.045);" % (WCOL[w], f(xe), f(yb)))
    ly, lx = 0.28, X0                                   # legend
    o.append(r"\draw[tbl, fill=wA] (%s,%s) rectangle (%s,%s);" % (f(lx), f(ly - 0.08), f(lx + 0.3), f(ly + 0.08)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {issues};" % (f(lx + 0.36), f(ly)))
    lx += 1.15
    o.append(r"\draw[sleep] (%s,%s) rectangle (%s,%s);" % (f(lx), f(ly - 0.08), f(lx + 0.3), f(ly + 0.08)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {sleeps on a pending source};" % (f(lx + 0.36), f(ly)))
    lx += 2.95
    o.append(r"\draw[line width=0.6pt, draw=wB!75!black] (%s,%s) -- (%s,%s);" % (f(lx), f(ly), f(lx + 0.3), f(ly)))
    o.append(r"\fill[wB!75!black] (%s,%s) circle (0.045);" % (f(lx + 0.3), f(ly)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {result in flight, written};" % (f(lx + 0.36), f(ly)))
    lx += 2.75
    o.append(r"\node[cell, text=red!70!black] at (%s,%s) {--};" % (f(lx + 0.12), f(ly)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {no runnable warp};" % (f(lx + 0.30), f(ly)))
    o.append(r"\node[subcap] at (%s,%s) {(a) Four warps under the issue rules (FPU latency 6; load latency schematic)};"
             % (f((PX[0] + PX[1]) / 2), f(-0.35)))
    return PX[1]


def panel_b(o, xstart):
    data, ncases = steps_data()
    PX = (xstart + 0.20, xstart + 0.20 + 6.75)
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(PX[0]), f(-0.05), f(PX[1]), f(4.55)))
    lx = PX[0] + 2.22                        # right edge of the step labels, bar origin
    bx1 = lx + 2.75                          # x of IPC 1
    vmin, vmax = 0.0, 1.0
    X = lambda v: lx + (v - vmin) / (vmax - vmin) * (bx1 - lx)
    cg, cr = bx1 + 0.42, bx1 + 1.20          # columns: IPC (geometric mean), range
    ytop, pitch, bh = 3.55, 0.46, 0.22
    yh = ytop + 0.45
    o.append(r"\node[cell, anchor=east] at (%s,%s) {\textbf{step}};" % (f(lx - 0.08), f(yh)))
    o.append(r"\node[cell] at (%s,%s) {\textbf{IPC}};" % (f(cg), f(yh)))
    o.append(r"\node[cell] at (%s,%s) {\textbf{range}};" % (f(cr), f(yh)))
    ybot = ytop - (len(data) - 1) * pitch - 0.30
    for v in (0.0, 0.25, 0.5, 0.75, 1.0):
        o.append(r"\draw[black!15, line width=0.3pt] (%s,%s) -- (%s,%s);" % (f(X(v)), f(ybot), f(X(v)), f(ytop + 0.24)))
        o.append(r"\node[cell, anchor=north] at (%s,%s) {%g};" % (f(X(v)), f(ybot - 0.03), v))
    o.append(r"\draw[black!60, line width=0.45pt] (%s,%s) -- (%s,%s);" % (f(lx), f(ybot), f(lx), f(ytop + 0.24)))
    o.append(r"\node[cell, anchor=north] at (%s,%s) {IPC (warp instructions per cycle)};" % (f((lx + bx1) / 2), f(ybot - 0.30)))
    for k, (lab, g, lo, hi) in enumerate(data):
        y = ytop - k * pitch
        o.append(r"\node[cell, anchor=east, align=right] at (%s,%s) {%s};" % (f(lx - 0.08), f(y), BR.join(lab)))
        o.append(r"\fill[bar] (%s,%s) rectangle (%s,%s);" % (f(lx), f(y - bh / 2), f(X(g)), f(y + bh / 2)))
        o.append(r"\draw[black!70, line width=0.45pt] (%s,%s) -- (%s,%s);" % (f(X(lo)), f(y), f(X(hi)), f(y)))
        for v in (lo, hi):
            o.append(r"\draw[black!70, line width=0.45pt] (%s,%s) -- (%s,%s);" % (f(X(v)), f(y - 0.07), f(X(v)), f(y + 0.07)))
        o.append(r"\node[cell] at (%s,%s) {%.2f};" % (f(cg), f(y), g))
        o.append(r"\node[cell, text=black!65] at (%s,%s) {%.2f--%.2f};" % (f(cr), f(y), lo, hi))
    # the steps are cumulative, over %d applications at board inputs: stated in the paper's text
    o.append(r"\node[subcap] at (%s,%s) {(b) IPC after each step};" % (f((PX[0] + PX[1]) / 2), f(-0.35)))


def main():
    o = [PRE]
    xr = panel_a(o)
    panel_b(o, xr)
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
