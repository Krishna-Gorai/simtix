#!/usr/bin/env python3
"""gen_launch_fig.py - from a kernel launch to warps in slots, from the RTL trace.

Reads traces/saxpy92_{fig,issue}.txt (fig_trace.py: kernels/figs/saxpy.S for N = 92
threads, board configuration: 8 lanes, 8 warp slots) and draws
  (a) the grid: 92 threads in 12 warps of eight lanes; the last warp's lanes 4-7 are masked
      by the spawner (tid >= N), and lane l of warp w starts with a0 = tid = 8w + l and the
      launch arguments in a1-a4;
  (b) the eight warp slots over the launch: when each warp is spawned (S) and finishes (D),
      the cycles in which it issues, and the issue slot shared by all warps.
Writes simtix_launch.tex; build with pdflatex.  Usage: python gen_launch_fig.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_launch.tex")
FIG = os.path.join(HERE, "traces", "saxpy92_fig.txt")
ISS = os.path.join(HERE, "traces", "saxpy92_issue.txt")
N, L = 92, 8

PRE = r"""% generated by gen_launch_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,patterns,decorations.pathreplacing}
\definecolor{cctrl}{HTML}{D6E0EC}
\definecolor{cctrlb}{HTML}{3B5675}
\definecolor{cwave}{HTML}{CFE2F3}
\definecolor{crefill}{HTML}{FCE5CD}
\definecolor{crefillb}{HTML}{C55A11}
\definecolor{cact}{HTML}{3B5675}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.6}{6.4}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  tbl/.style={draw=black!70, line width=0.3pt},
  lbl/.style={font=\fs, inner sep=0.5pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left},
  code/.style={font=\fss\ttfamily, inner sep=0.5pt},
  panel/.style={draw=black!40, dashed, rounded corners=3pt, fill=black!1, line width=0.5pt},
  subcap/.style={font=\fs, inner sep=1pt},
  arr/.style={-{Latex[length=1.2mm, width=0.9mm]}, line width=0.45pt}]
"""


def f(x):
    return "%.3f" % x


def parse():
    spawn, done, issues = [], {}, []
    for line in open(FIG):
        p = line.split()
        if not p:
            continue
        if p[0] == 'S':
            spawn.append((int(p[1]), int(p[2]), int(p[3]) // L, p[4]))
        elif p[0] == 'D':
            done.setdefault(int(p[2]), []).append(int(p[1]))
        elif p[0] == 'X' and p[5] == 'issue':
            issues.append((int(p[1]), int(p[2])))
    end = next(int(l.split()[1]) for l in open(ISS) if l.startswith('E'))
    # pair each spawn with the slot's next finish
    bars = []
    for c, slot, w, mask in spawn:
        d = min(x for x in done[slot] if x > c)
        bars.append(dict(slot=slot, warp=w, s=c, d=d, lanes=mask.count('1')))
    return bars, issues, end


def panel_a(o, y0, y1):
    ax0, ax1 = -0.10, 6.55
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(ax0), f(y0), f(ax1), f(y1)))
    nw = (N + L - 1) // L
    cw, gap, gy, ch = 0.058, 0.055, y1 - 0.95, 0.20
    o.append(r"\node[lbl, anchor=west] at (0.05,%s) {kernel launch: $N = %d$ threads, warps of $L = %d$ lanes};"
             % (f(y1 - 0.22), N, L))
    o.append(r"\node[note, anchor=west, text=black!65] at (0.05,%s) {one cell per thread; grouped into warps in thread order};"
             % f(y1 - 0.48))
    xg = []
    for w in range(nw):
        x = 0.12 + w * (L * cw + gap)
        xg.append(x)
        for l in range(L):
            t = w * L + l
            style = "tbl, fill=cact" if t < N else "tbl, pattern=north east lines, pattern color=black!60"
            o.append(r"\draw[%s] (%s,%s) rectangle (%s,%s);" % (style, f(x + l * cw), f(gy), f(x + (l + 1) * cw), f(gy + ch)))
        o.append(r"\node[note] at (%s,%s) {w%d};" % (f(x + L * cw / 2), f(gy - 0.13), w))
    for w in (0, 5, 11):
        o.append(r"\node[note, text=black!60] at (%s,%s) {%d};" % (f(xg[w]), f(gy + ch + 0.11), w * L))
    o.append(r"\node[note, text=black!60, anchor=west] at (%s,%s) {tid};" % (f(xg[-1] + L * cw + 0.03), f(gy + ch + 0.11)))
    # zoom: the last warp, lane by lane
    zx, zy = 0.95, gy - 0.48                       # table's upper-left corner
    cols = [("lane", 0.55), ("tid = a0", 0.95), (r"a1\,--\,a4", 1.40), ("lane is", 0.85)]
    tw = sum(w for _, w in cols)
    o.append(r"\draw[black!45, line width=0.35pt] (%s,%s) -- (%s,%s);" % (f(xg[-1]), f(gy), f(zx), f(zy)))
    o.append(r"\draw[black!45, line width=0.35pt] (%s,%s) -- (%s,%s);" % (f(xg[-1] + L * cw), f(gy), f(zx + tw), f(zy)))
    rh = 0.205
    x = zx
    for name, w in cols:
        o.append(r"\draw[tbl, fill=black!6] (%s,%s) rectangle (%s,%s);" % (f(x), f(zy - rh), f(x + w), f(zy)))
        o.append(r"\node[note] at (%s,%s) {%s};" % (f(x + w / 2), f(zy - rh / 2), name))
        x += w
    wl = nw - 1
    for l in range(L):
        y = zy - (l + 1) * rh
        t = wl * L + l
        vals = [str(l), str(t), "x, y, \\&a, $N$", "active" if t < N else "masked"]
        x = zx
        for (name, w), v in zip(cols, vals):
            fill = "white" if t < N else "black!8"
            o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (fill, f(x), f(y - rh), f(x + w), f(y)))
            o.append(r"\node[note] at (%s,%s) {%s};" % (f(x + w / 2), f(y - rh / 2), v))
            x += w
    o.append(r"\node[note, anchor=east, align=right] at (%s,%s) {warp %d,\\lane by lane};" % (f(zx - 0.05), f(zy - 4.5 * rh), wl))
    o.append(r"\node[note, anchor=west, text=black!65, align=left] at (0.05,%s) {The spawner masks the lanes with tid $\geq N$. A register not yet written\\reads its start value: the thread ID in a0, the launch arguments in\\a1\,--\,a4 (the same in every lane), else zero.};"
             % f(zy - (L + 1) * rh - 0.50))
    o.append(r"\node[subcap] at (%s,%s) {(a) Threads, warps and lanes};" % (f((ax0 + ax1) / 2), f(y0 - 0.30)))


def panel_b(o, y0, y1, bars, issues, end):
    bx0, bx1 = 6.75, 18.15
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(bx0), f(y0), f(bx1), f(y1)))
    X0, xs = 7.75, (17.75 - 7.75) / end           # cm per cycle
    rh, top = 0.36, y1 - 0.50
    nslot = 8
    X = lambda c: X0 + c * xs
    for k in range(nslot):
        y = top - (k + 1) * rh
        if k % 2 == 0:
            o.append(r"\fill[black!4] (%s,%s) rectangle (%s,%s);" % (f(X0), f(y), f(X(end + 1)), f(y + rh)))
        o.append(r"\node[lbl, anchor=east] at (%s,%s) {slot %d};" % (f(X0 - 0.06), f(y + rh / 2), k))
    for b in bars:
        y = top - (b['slot'] + 1) * rh
        refill = b['s'] > 8
        fill, bd = ("crefill", "crefillb") if refill else ("cwave", "cctrlb")
        o.append(r"\draw[line width=0.4pt, fill=%s, draw=%s] (%s,%s) rectangle (%s,%s);"
                 % (fill, bd, f(X(b['s'])), f(y + 0.05), f(X(b['d'] + 1)), f(y + rh - 0.05)))
        lab = "w%d" % b['warp'] + (r" (%d lanes)" % b['lanes'] if b['lanes'] < L else "")
        o.append(r"\node[note, anchor=west] at (%s,%s) {%s};" % (f(X(b['s']) + 0.03), f(y + rh / 2 + 0.06), lab))
    for c, slot in issues:                          # the cycles a warp issues
        y = top - (slot + 1) * rh
        o.append(r"\draw[cact, line width=0.55pt] (%s,%s) -- (%s,%s);" % (f(X(c + 0.5)), f(y + 0.07), f(X(c + 0.5)), f(y + 0.15)))
    # the shared issue slot
    yi = top - nslot * rh - 0.36
    o.append(r"\node[lbl, anchor=east] at (%s,%s) {issue};" % (f(X0 - 0.06), f(yi + 0.09)))
    o.append(r"\draw[black!30, line width=0.3pt] (%s,%s) rectangle (%s,%s);" % (f(X0), f(yi), f(X(end + 1)), f(yi + 0.18)))
    for c, slot in issues:
        o.append(r"\draw[cact, line width=0.55pt] (%s,%s) -- (%s,%s);" % (f(X(c + 0.5)), f(yi), f(X(c + 0.5)), f(yi + 0.18)))
    n_issue = len(issues)
    # time axis
    ya = yi - 0.10
    for c in range(0, end + 1, 50):
        o.append(r"\draw[black!50, line width=0.3pt] (%s,%s) -- (%s,%s);" % (f(X(c)), f(ya), f(X(c)), f(ya - 0.06)))
        o.append(r"\node[note] at (%s,%s) {%d};" % (f(X(c)), f(ya - 0.17), c))
    o.append(r"\node[note, anchor=east] at (%s,%s) {cycle};" % (f(X0 - 0.06), f(ya - 0.17)))
    # events above the slots: GO, the first wave, DONE
    yt = top + 0.10
    o.append(r"\draw[decorate, decoration={brace, amplitude=2pt}, line width=0.4pt] (%s,%s) -- (%s,%s);"
             % (f(X(0)), f(yt), f(X(8)), f(yt)))
    o.append(r"\node[note, anchor=south west] at (%s,%s) {GO: the spawner places warps 0\,--\,7, one per cycle};" % (f(X(0) - 0.05), f(yt + 0.07)))
    o.append(r"\draw[cctrlb, line width=0.5pt] (%s,%s) -- (%s,%s);" % (f(X(end + 1)), f(top - nslot * rh), f(X(end + 1)), f(yt + 0.02)))
    o.append(r"\node[note, anchor=south east] at (%s,%s) {DONE};" % (f(X(end + 1)), f(yt + 0.07)))
    # legend
    ly = y0 + 0.22
    lx = X0 - 0.6
    for fill, bd, text in (("cwave", "cctrlb", "first wave"), ("crefill", "crefillb", "refills a finished slot")):
        o.append(r"\draw[line width=0.4pt, fill=%s, draw=%s] (%s,%s) rectangle (%s,%s);" % (fill, bd, f(lx), f(ly - 0.08), f(lx + 0.24), f(ly + 0.08)))
        o.append(r"\node[note, anchor=west] at (%s,%s) {%s};" % (f(lx + 0.28), f(ly), text))
        lx += 1.55 if fill == "cwave" else 2.65
    o.append(r"\draw[cact, line width=0.55pt] (%s,%s) -- (%s,%s);" % (f(lx + 0.1), f(ly - 0.08), f(lx + 0.1), f(ly + 0.08)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {the warp issues an instruction (%d issues in %d cycles)};"
             % (f(lx + 0.2), f(ly), n_issue, end))
    o.append(r"\node[subcap] at (%s,%s) {(b) The eight warp slots during the launch};" % (f((bx0 + bx1) / 2), f(y0 - 0.30)))


def main():
    bars, issues, end = parse()
    assert len(bars) == (N + L - 1) // L
    o = [PRE]
    y0, y1 = -0.05, 4.70
    panel_a(o, y0, y1)
    panel_b(o, y0, y1, bars, issues, end)
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT, "warps", len(bars), "issues", len(issues), "end", end)


if __name__ == "__main__":
    main()
