#!/usr/bin/env python3
"""gen_launch_fig.py - a SAXPY launch for 92 threads, from the RTL trace (the paper's Fig. 2).

  (a) the grid: 92 threads in 12 warps of eight lanes; the spawner masks lanes 4-7 of warp 11
      (tid >= N), and each lane starts with a0 = tid and the launch arguments in a1-a4
      (their values in the run are tabulated for warp 11);
  (b) the whole launch as a waveform: busy, the issue of a warp instruction, the eight warp
      slots (bus: the warp in the slot; shade: running, asleep on the register scoreboard, or
      parked until memory answers its store), the AXI4 read and write handshakes and DONE;
      the three windows of Fig. 3 are marked.
Reads traces/saxpy92_*.txt through launch_trace.py.
Writes simtix_launch.tex; build with pdflatex.  Usage: python gen_launch_fig.py
"""
import os

from launch_trace import NSLOT, Launch, L, N
from wavetikz import SLOPE, Axis, bit, bus, f, label

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_launch.tex")
ARGS = [("a1", "\\&x", 0x10000000), ("a2", "\\&y", 0x10001000), ("a3", "\\&a", 0x10002000)]
WINDOWS = [(0, 23, "3(a)"), (44, 67, "3(b)"), (96, 119, "3(c)")]   # gen_launch_wave_fig.py

PRE = r"""% generated by gen_launch_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{patterns,decorations.pathreplacing}
\definecolor{cact}{HTML}{3B5675}
\definecolor{csleep}{HTML}{D9D9D9}
\definecolor{cpark}{HTML}{F8CBAD}
\definecolor{cwin}{HTML}{2A78D6}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.6}{6.4}\selectfont}
\newcommand{\fv}{\fontsize{5.3}{5.8}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  wire/.style={draw=black, line width=0.4pt, line join=round},
  tbl/.style={draw=black!60, line width=0.3pt},
  gridline/.style={draw=black!12, line width=0.25pt},
  lbl/.style={font=\fs, inner sep=0.5pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left},
  subcap/.style={font=\fs, inner sep=1pt}]
"""


def panel_a(o, ytop):
    nw = (N + L - 1) // L
    cw, gap, ch = 0.105, 0.105, 0.30
    x0, gy = 0.15, ytop - 0.95
    o.append(r"\node[lbl, anchor=west] at (%s,%s) {Grid: $N=%d$ threads in warps of $L=%d$ lanes, "
             r"lane $l$ of warp $w$ runs thread $8w+l$ (one cell per thread)};" % (f(x0 - 0.05), f(ytop - 0.18), N, L))
    xg = []
    for w in range(nw):
        x = x0 + w * (L * cw + gap)
        xg.append(x)
        for l in range(L):
            t = w * L + l
            st = "tbl, fill=cact" if t < N else "tbl, pattern=north east lines, pattern color=black!55"
            o.append(r"\draw[%s] (%s,%s) rectangle (%s,%s);" % (st, f(x + l * cw), f(gy), f(x + (l + 1) * cw), f(gy + ch)))
        o.append(r"\node[note] at (%s,%s) {w%d};" % (f(x + L * cw / 2), f(gy - 0.15), w))
        o.append(r"\node[font=\fv, text=black!60] at (%s,%s) {%d};" % (f(x + 0.02), f(gy + ch + 0.12), w * L))
    o.append(r"\node[font=\fv, text=black!60, anchor=west] at (%s,%s) {tid};"
             % (f(xg[-1] + L * cw + 0.05), f(gy + ch + 0.12)))
    o.append(r"\draw[tbl, pattern=north east lines, pattern color=black!55] (%s,%s) rectangle (%s,%s);"
             % (f(x0), f(gy - 0.52), f(x0 + 0.22), f(gy - 0.38)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {masked by the spawner: threads 92 to 95 lie past $N$};"
             % (f(x0 + 0.27), f(gy - 0.45)))
    o.append(r"\draw[tbl, fill=cact] (%s,%s) rectangle (%s,%s);" % (f(x0 + 5.0), f(gy - 0.52), f(x0 + 5.22), f(gy - 0.38)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {active thread};" % (f(x0 + 5.27), f(gy - 0.45)))
    # warp 11 lane by lane: the start values of its registers in this run
    tx, ty = 11.25, ytop - 0.32
    cols = [("lane", 0.42), ("a0 = tid", 0.66)] + [("%s = %s" % (r, n), 1.12) for r, n, _ in ARGS] + \
           [("a4 = $N$", 0.66), ("lane is", 0.72)]
    rh = 0.235
    o.append(r"\draw[black!45, line width=0.35pt] (%s,%s) -- (%s,%s);" % (f(xg[-1] + L * cw), f(gy + ch), f(tx), f(ty)))
    o.append(r"\draw[black!45, line width=0.35pt] (%s,%s) -- (%s,%s);" % (f(xg[-1] + L * cw), f(gy), f(tx), f(ty - 9 * rh)))
    x = tx
    for name, w in cols:
        o.append(r"\draw[tbl, fill=black!6] (%s,%s) rectangle (%s,%s);" % (f(x), f(ty - rh), f(x + w), f(ty)))
        o.append(r"\node[font=\fv] at (%s,%s) {%s};" % (f(x + w / 2), f(ty - rh / 2), name))
        x += w
    for l in range(L):
        t = (nw - 1) * L + l
        vals = [str(l), str(t)] + ["0x%08X" % v for _, _, v in ARGS] + [str(N), "active" if t < N else "masked"]
        x, y = tx, ty - (l + 1) * rh
        for (name, w), v in zip(cols, vals):
            fill = "white" if t < N else "black!8"
            o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (fill, f(x), f(y - rh), f(x + w), f(y)))
            o.append(r"\node[font=\fv\ttfamily] at (%s,%s) {%s};" % (f(x + w / 2), f(y - rh / 2), v))
            x += w
    o.append(r"\node[note, anchor=south] at (%s,%s) {warp 11: start values of the registers};"
             % (f(tx + sum(w for _, w in cols) / 2), f(ty + 0.02)))
    ybot = ty - 9 * rh - 0.05
    o.append(r"\node[subcap] at (9.0,%s) {(a) Threads, warps and lanes};" % f(ybot - 0.18))
    return ybot - 0.45


def panel_b(o, T, ytop):
    end = T.end
    ax = Axis(1.55, -4, end + 4, (17.85 - 1.55) / (end + 9))
    pitch, h = 0.285, 0.19
    rows = [("busy", "bit", set(range(0, end + 1))),
            ("issue", "bit", {c for c, (s, pc, k) in T.x.items() if k == "issue"}),
            None] + [("slot[%d]" % k, "slot", k) for k in range(NSLOT)] + [None,
            ("axi.ar", "bit", set(T.ar)), ("axi.r", "bit", set(T.r)),
            ("axi.aw", "bit", set(T.aw)), ("axi.b", "bit", set(T.b)), None,
            ("done", "bit", {end})]
    nrow = sum(1 for r in rows if r) + 0.45 * sum(1 for r in rows if r is None)
    ybot = ytop - 0.55 - nrow * pitch
    # the windows of Fig. 3
    for c0, c1, name in WINDOWS:
        o.append(r"\fill[cwin, opacity=0.10] (%s,%s) rectangle (%s,%s);" % (f(ax.x(c0)), f(ybot + 0.02), f(ax.x(c1 + 1)), f(ytop - 0.34)))
        o.append(r"\node[font=\fv, text=cwin] at (%s,%s) {Fig.~%s};" % (f((ax.x(c0) + ax.x(c1 + 1)) / 2), f(ytop - 0.24), name))
    for c in range(0, end + 1, 10):
        o.append(r"\draw[gridline] (%s,%s) -- (%s,%s);" % (f(ax.x(c)), f(ybot + 0.02), f(ax.x(c)), f(ytop - 0.34)))
    y = ytop - 0.40
    for r in rows:
        if r is None:
            y -= 0.45 * pitch
            continue
        name, kind, v = r
        y -= pitch
        ys = y + (pitch - h) / 2
        label(o, ax, ys, h, name)
        if kind == "bit":
            bit(o, ax, ys, h, v)
        else:
            slot_row(o, ax, ys, h, T, v)
    # cycle axis
    for c in range(0, end + 1, 25):
        o.append(r"\draw[black!50, line width=0.3pt] (%s,%s) -- (%s,%s);" % (f(ax.x(c)), f(ybot), f(ax.x(c)), f(ybot - 0.06)))
        o.append(r"\node[font=\fv] at (%s,%s) {%d};" % (f(ax.x(c)), f(ybot - 0.16), c))
    o.append(r"\node[font=\fv, anchor=east] at (%s,%s) {cycle};" % (f(ax.x(0) - 0.10), f(ybot - 0.16)))
    # legend
    ly, lx = ybot - 0.45, 1.55
    for fill, text in (("white", "running"), ("csleep", "asleep on the register scoreboard"),
                       ("cpark", "parked until memory answers its store")):
        o.append(r"\draw[wire, fill=%s] (%s,%s) rectangle (%s,%s);" % (fill, f(lx), f(ly - 0.07), f(lx + 0.30), f(ly + 0.07)))
        o.append(r"\node[note, anchor=west] at (%s,%s) {%s};" % (f(lx + 0.35), f(ly), text))
        lx += 0.65 + 0.100 * len(text)
    o.append(r"\node[note, anchor=west] at (%s,%s) {slot: bus value = the warp in the slot, from its spawn to its \texttt{ecall}};"
             % (f(lx + 0.2), f(ly)))
    o.append(r"\node[subcap] at (9.0,%s) {(b) The whole launch: %d warp instructions in %d cycles};"
             % (f(ly - 0.35), sum(1 for c, (s, pc, k) in T.x.items() if k == "issue"), end))


def slot_row(o, ax, y, h, T, k):
    s = min(SLOPE, ax.cw * 0.2)
    cyc = range(ax.c0, ax.c1 + 1)
    warps = [T.warp_in(k, c) if T.state(k, c) else None for c in cyc]
    fill = {"sleep": "csleep", "park": "cpark"}
    for i, c in enumerate(cyc):
        st = T.state(k, c)
        if warps[i] is None or st not in fill:
            continue
        first = i == 0 or warps[i - 1] != warps[i]
        last = i == len(warps) - 1 or warps[i + 1] != warps[i]
        xa = ax.x(c) + (s if first else 0)
        xb = ax.x(c + 1) - (s if last else 0)
        o.append(r"\fill[%s] (%s,%s) rectangle (%s,%s);" % (fill[st], f(xa), f(y), f(xb), f(y + h)))
    lanes = {w: n for _, _, w, n in T.spawn}
    bus(o, ax, y, h, warps, fills=lambda v: "fill=none",
        text=lambda v: r"\fv w%d%s" % (v, "" if lanes[v] == L else ", %d lanes" % lanes[v]), font=r"\fv", min_w=0.3)


def main():
    T = Launch()
    o = [PRE]
    y = panel_a(o, 0.0)
    panel_b(o, T, y)
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
