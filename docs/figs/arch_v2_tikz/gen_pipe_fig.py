#!/usr/bin/env python3
"""gen_pipe_fig.py - one warp's SAXPY through the pipeline, cycle by cycle, from the RTL trace.

Reads traces/saxpy1_{fig,issue}.txt (fig_trace.py: kernels/figs/saxpy.S on one eight-lane
warp, board configuration, 24-cycle AXI4 memory model) and draws, for each instruction, the
cycles it spends in each stage: fetch (F), issue and execute (X), the stack update (B), the
memory engine (context and coalescer), the L1, the AXI4 master and memory, the FPU, and the
register write; an X that is held back by the register scoreboard is drawn as a wait, and the
warp's sleep until a result is written as a dotted line. Stretches in which only memory is
busy are cut from the time axis (axis breaks).
Writes simtix_pipe.tex; build with pdflatex.  Usage: python gen_pipe_fig.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(HERE, "simtix_pipe.tex")
FIG = os.path.join(HERE, "traces", "saxpy1_fig.txt")
ISS = os.path.join(HERE, "traces", "saxpy1_issue.txt")
SRC = os.path.join(ROOT, "kernels", "figs", "saxpy.S")
KEEP = [(0, 19), (34, 49), (69, 92), (114, 121)]   # cycles shown; the gaps are memory waits
CW, BRK = 0.205, 0.42                              # cm per cycle, width of an axis break
X0, RH = 3.05, 0.34                                # left edge of cycle 0, row height

PRE = r"""% generated by gen_pipe_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,patterns,decorations.pathmorphing}
\definecolor{cctrl}{HTML}{D6E0EC}
\definecolor{cctrlb}{HTML}{3B5675}
\definecolor{cfpu}{HTML}{FFE9A8}
\definecolor{cfpub}{HTML}{BF9000}
\definecolor{cme}{HTML}{FBE5D6}
\definecolor{cmeb}{HTML}{C55A11}
\definecolor{cl1}{HTML}{F4B183}
\definecolor{cddr}{HTML}{EAD1DC}
\definecolor{cddrb}{HTML}{8E5572}
\definecolor{cwb}{HTML}{D9EAD3}
\definecolor{cwbb}{HTML}{548235}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.6}{6.4}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  seg/.style={line width=0.4pt, inner sep=0pt},
  lbl/.style={font=\fs, inner sep=0.5pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left},
  code/.style={font=\fss\ttfamily, inner sep=0.5pt, anchor=west},
  panel/.style={draw=black!40, dashed, rounded corners=3pt, fill=black!1, line width=0.5pt},
  arr/.style={-{Latex[length=1.2mm, width=0.9mm]}, line width=0.45pt}]
"""
STYLE = {  # stage -> (fill, border, label)
    'F': ('cctrl', 'cctrlb', 'F'), 'X': ('cctrl', 'cctrlb', 'X'), 'B': ('cctrl', 'cctrlb', 'B'),
    'wait': ('white', 'cctrlb', ''), 'ME': ('cme', 'cmeb', 'ME'), 'L1': ('cl1', 'cmeb', 'L1'),
    'DDR': ('cddr', 'cddrb', ''), 'FPU': ('cfpu', 'cfpub', 'FPU'), 'WB': ('cwb', 'cwbb', 'W'),
}


def f(x):
    return "%.3f" % x


def xc(c):
    """left edge of cycle c on the compressed axis"""
    x = X0
    for i, (a, b) in enumerate(KEEP):
        if c <= b or i == len(KEEP) - 1:
            return x + (max(c, a) - a) * CW
        x += (b - a + 1) * CW + BRK
    return x


def program():
    ins = []
    for line in open(SRC):
        s = line.split('#')[0].strip()
        s = re.sub(r'^\d+:\s*', '', s)
        if s and not s.startswith('.') and not s.endswith(':'):
            ins.append(re.sub(r'\s+', ' ', s, count=1))
    return ins


def parse(fn):
    """events by letter; the stage trace and the issue trace use some letters differently
    (X, R, W, U), so each file gets its own table"""
    ev = {}
    for line in open(fn):
        p = line.split()
        if len(p) >= 2 and p[1].isdigit():
            ev.setdefault(p[0], []).append(p[1:])
    return ev


def main():
    ins = program()
    ev, iv = parse(FIG), parse(ISS)
    pc_row = {4 * i: i for i in range(len(ins))}
    segs = {i: [] for i in range(len(ins))}          # row -> [(stage, c0, c1)]
    sleeps = {i: [] for i in range(len(ins))}
    for c, w, pc, *_ in ev['F']:
        segs[pc_row[int(pc, 16)]].append(('F', int(c), int(c)))
    last_wait = {}
    for c, w, pc, mask, *kind in ev['X']:
        r, c = pc_row[int(pc, 16)], int(c)
        if kind and kind[0] == 'wait':
            segs[r].append(('wait', c, c))
            last_wait[r] = c
        else:
            segs[r].append(('X', c, c))
    # sleeps: from a held-back X to the next fetch of the same instruction
    for r in range(len(ins)):
        fs = sorted(c for s, c, _ in segs[r] if s == 'F')
        for s, c, _ in list(segs[r]):
            if s == 'wait':
                nxt = min(x for x in fs if x > c)
                if nxt > c + 1:
                    sleeps[r].append((c + 1, nxt - 1))
    for c, w, kind, taken, mask in ev['B']:
        x_issue = int(c) - 1
        r = next(r for r in segs for s, a, _ in segs[r] if s == 'X' and a == x_issue)
        segs[r].append(('B', int(c), int(c)))
    # memory ops, in order: context entry (M) -> L1 request (Q) -> L1 to AXI4 master (L) ->
    # reply to the L1 (N) -> response to the engine (A); a load then writes its register (W)
    ms, qs, ls, ns, as_ = (ev[k] for k in ('M', 'Q', 'L', 'N', 'A'))
    assert len(ms) == len(qs) == len(ls) == len(ns) == len(as_)
    loads_wb = [int(e[0]) for e in iv['W']]        # a load writes its register
    li = 0
    mem_rows = []
    for (mc, _, pc), q, l, n, a in zip(ms, qs, ls, ns, as_):
        r = pc_row[int(pc, 16)]
        mc, qc, lc, nc, ac = int(mc), int(q[0]), int(l[0]), int(n[0]), int(a[0])
        we = q[3] == '1'
        segs[r] += [('ME', mc + 1, qc - 1), ('L1', qc, lc), ('DDR', lc + 1, nc)]
        if not we:
            segs[r].append(('WB', loads_wb[li], loads_wb[li]))
            li += 1
        mem_rows.append((r, lc + 1, nc, we, ac))
    # the FPU op: six cycles from issue to its result, then the register write (R event)
    fma_row = next(i for i, s in enumerate(ins) if s.startswith('fmadd'))
    x_fma = max(a for s, a, _ in segs[fma_row] if s == 'X')
    r_fma = min(int(e[0]) for e in iv['R'] if int(e[0]) > x_fma)
    segs[fma_row] += [('FPU', x_fma + 1, x_fma + 6), ('WB', r_fma, r_fma)]
    resume = int(iv['U'][-1][0]) if 'U' in iv else None   # a parked warp resumes
    end = int(iv['E'][0][0])

    o = [PRE]
    n = len(ins)
    ytop = n * RH
    xe = xc(KEEP[-1][1]) + CW
    o.append(r"\draw[panel] (-0.10,-1.62) rectangle (%s,%s);" % (f(xe + 0.55), f(ytop + 0.50)))
    for r, s in enumerate(ins):
        y = ytop - (r + 1) * RH
        if r % 2 == 0:
            o.append(r"\fill[black!4] (%s,%s) rectangle (%s,%s);" % (f(X0), f(y), f(xe), f(y + RH)))
        op, _, args = s.partition(' ')
        o.append(r"\node[code, text=black!55] at (0.0,%s) {%x};" % (f(y + RH / 2), 4 * r))
        o.append(r"\node[code] at (0.30,%s) {%s};" % (f(y + RH / 2), op))
        o.append(r"\node[code] at (1.28,%s) {%s};" % (f(y + RH / 2), args))
        for a, b in sleeps[r]:
            o.append(r"\draw[cctrlb, densely dotted, line width=0.6pt] (%s,%s) -- (%s,%s);"
                     % (f(xc(a)), f(y + RH / 2), f(xc(b) + CW), f(y + RH / 2)))
        for st, a, b in segs[r]:
            fill, bd, lab = STYLE[st]
            pad = 0.045
            xa, xb = xc(a), xc(b) + CW
            extra = ", pattern=north east lines, pattern color=cctrlb!70" if st == 'wait' else ""
            o.append(r"\draw[seg, fill=%s, draw=%s%s] (%s,%s) rectangle (%s,%s);"
                     % (fill, bd, extra, f(xa), f(y + pad), f(xb), f(y + RH - pad)))
            if lab and xb - xa >= CW * 0.99:
                o.append(r"\node[note] at (%s,%s) {%s};" % (f((xa + xb) / 2), f(y + RH / 2), lab))
    # the DDR bars' label, in their widest piece between axis breaks
    for r, a, b, we, ac in mem_rows:
        y = ytop - (r + 1) * RH + RH / 2
        pieces = [(max(a, ka), min(b, kb)) for ka, kb in KEEP if max(a, ka) <= min(b, kb)]
        pa, pb = max(pieces, key=lambda p: p[1] - p[0])
        if (pb - pa + 1) * CW >= 0.62:
            o.append(r"\node[note] at (%s,%s) {%s};"
                     % (f((xc(pa) + xc(pb) + CW) / 2), f(y), "write" if we else "read"))
    # axis breaks (white bands over every row), with the number of cycles cut
    for i in range(len(KEEP) - 1):
        xb = xc(KEEP[i][1]) + CW
        o.append(r"\fill[white] (%s,%s) rectangle (%s,%s);" % (f(xb + 0.05), f(-0.02), f(xb + BRK - 0.05), f(ytop + 0.02)))
        for dx in (0.05, BRK - 0.05):
            o.append(r"\draw[black!55, line width=0.4pt, decorate, decoration={zigzag, segment length=1.6mm, amplitude=0.35mm}] (%s,%s) -- (%s,%s);"
                     % (f(xb + dx), f(-0.02), f(xb + dx), f(ytop + 0.02)))
        hidden = KEEP[i + 1][0] - KEEP[i][1] - 1
        o.append(r"\node[note, text=black!60, align=center] at (%s,%s) {%d cycles\\not shown};" % (f(xb + BRK / 2), f(ytop + 0.22), hidden))
    # time axis: every fifth cycle, and the last
    o.append(r"\node[note, anchor=east] at (%s,%s) {cycle};" % (f(X0 - 0.05), f(-0.22)))
    for a, b in KEEP:
        for c in range(a, b + 1):
            if c % 5 == 0:
                o.append(r"\node[note] at (%s,%s) {%d};" % (f(xc(c) + CW / 2), f(-0.22), c))
                o.append(r"\draw[black!40, line width=0.3pt] (%s,0) -- (%s,-0.07);" % (f(xc(c) + CW / 2), f(xc(c) + CW / 2)))
    # the end of the launch: DONE
    o.append(r"\node[note, anchor=west] at (%s,%s) {DONE};" % (f(xc(end) + 0.02), f(ytop - n * RH + RH / 2)))
    # numbered notes, explained under the legend
    def mark(row, c, k):
        y = ytop - (row + 1) * RH + RH / 2
        o.append(r"\node[circle, draw=black!70, fill=white, inner sep=0.2pt, minimum size=2.7mm, font=\fss] at (%s,%s) {%d};"
                 % (f(xc(c) + CW / 2), f(y), k))
    r_y = next(i for i, s in enumerate(ins) if s.startswith('flw f2'))
    w_y = min(a for s, a, _ in segs[r_y] if s == 'wait')
    mark(r_y, w_y + 2, 1)
    w_f = min(a for s, a, _ in segs[fma_row] if s == 'wait')
    mark(fma_row, w_f + 2, 2)
    st_row = next(i for i, s in enumerate(ins) if s.startswith('fsw'))
    st_end = max(b for st, a, b in segs[st_row] if st == 'DDR')
    mark(st_row, st_end + 2, 3)
    # legend, two rows, and the notes
    rows = [[('F', 'fetch'), ('X', 'issue and execute'), ('B', 'stack update'),
             ('wait', 'held back (scoreboard)'), ('sleep', 'warp asleep')],
            [('ME', 'memory engine'), ('L1', 'L1'),
             ('DDR', 'AXI4 master and DDR4'), ('FPU', 'FPU'), ('WB', 'register write')]]
    for k, items in enumerate(rows):
        ly = -0.62 - 0.30 * k
        for i, (st, text) in enumerate(items):
            lx = X0 + 2.75 * i
            if st == 'sleep':
                o.append(r"\draw[cctrlb, densely dotted, line width=0.6pt] (%s,%s) -- (%s,%s);"
                         % (f(lx), f(ly), f(lx + 0.24), f(ly)))
            else:
                fill, bd, lab = STYLE[st]
                extra = ", pattern=north east lines, pattern color=cctrlb!70" if st == 'wait' else ""
                o.append(r"\draw[seg, fill=%s, draw=%s%s] (%s,%s) rectangle (%s,%s);"
                         % (fill, bd, extra, f(lx), f(ly - 0.09), f(lx + 0.24), f(ly + 0.09)))
            o.append(r"\node[note, anchor=west] at (%s,%s) {%s};" % (f(lx + 0.28), f(ly), text))
    notes = (r"\textcircled{\raisebox{-0.2pt}{1}}~the third load waits: two loads of the warp are in flight;\quad"
             r"\textcircled{\raisebox{-0.2pt}{2}}~the FMA waits for $x$ and $y$;\quad"
             r"\textcircled{\raisebox{-0.2pt}{3}}~the store holds the warp until DDR4 answers the write")
    o.append(r"\node[note, anchor=west] at (%s,%s) {%s};" % (f(X0), f(-1.46), notes))
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT, "end cycle", end)


if __name__ == "__main__":
    main()
