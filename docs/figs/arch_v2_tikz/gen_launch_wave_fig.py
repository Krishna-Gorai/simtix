#!/usr/bin/env python3
"""gen_launch_wave_fig.py - cycle-by-cycle waveforms of the SAXPY launch (the paper's Fig. 3).

Three windows of the RTL trace of Fig. 2 (launch_trace.py): the clock, the spawner, fetch and
issue, the eight warp slots, the L1 and the AXI4 channels and the register-file writes, one
column per cycle. Every value is read from the trace.
Writes simtix_launch_wave.tex; build with pdflatex.  Usage: python gen_launch_wave_fig.py
"""
import os

from launch_trace import NSLOT, Launch
from wavetikz import SLOPE, Axis, bit, bus, clock, f, label

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_launch_wave.tex")
WINDOWS = [(0, 23, "(a) Cycles 0 to 23: the spawner fills the slots, the warps issue in turn, "
                   "and the eight loads of $a$ share one miss"),
           (44, 67, "(b) Cycles 44 to 67: the loads of $x$ and $y$ go to memory, and the warps "
                    "fall asleep on their FMAs"),
           (96, 119, "(c) Cycles 96 to 119: the lines return, the warps wake, and the FMAs and "
                     "the stores issue")]
X0, CW = 1.55, 0.680                   # left edge of the first cycle, cm per cycle
PITCH, H = 0.285, 0.200                # row pitch and signal height

PRE = r"""% generated by gen_launch_wave_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{patterns}
\definecolor{csleep}{HTML}{D9D9D9}
\definecolor{cpark}{HTML}{F8CBAD}
\definecolor{cread}{HTML}{DDEBF7}
\definecolor{cwrite}{HTML}{FCE4D6}
\definecolor{cmiss}{HTML}{F4B6B6}
\definecolor{cjoin}{HTML}{FFE699}
\definecolor{chit}{HTML}{C6E0B4}
\definecolor{cld}{HTML}{C6E0B4}
\definecolor{cfpu}{HTML}{FFE699}
\definecolor{cspawn}{HTML}{D6E0EC}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.6}{6.4}\selectfont}
\newcommand{\fv}{\fontsize{5.3}{5.8}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  wire/.style={draw=black, line width=0.4pt, line join=round},
  gridline/.style={draw=black!12, line width=0.25pt},
  sep/.style={draw=black!35, line width=0.3pt},
  subcap/.style={font=\fs, inner sep=1pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left}]
"""

HELD = "fill=white, pattern=north east lines, pattern color=black!45"


def window(o, T, c0, c1, ytop, title):
    ax = Axis(X0, c0, c1, CW)
    cyc = range(c0, c1 + 1)
    rows = []                                    # (name, kind, values / set, fills, text)
    rows.append(("clk", "clock", None, None, None))
    rows.append(("spawn", "bus", [("w%d" % next(w for s, k, w, _ in T.spawn if s == c))
                                  if any(s == c for s, *_ in T.spawn) else None for c in cyc],
                 lambda v: "fill=cspawn", None))
    rows.append(("fetch", "bus", [("w%d" % T.fetched(c)) if T.fetched(c) is not None else None
                                  for c in cyc], None, None))
    iss = [T.issued(c) for c in cyc]
    rows.append(("issue", "bus", [("w%d" % i[0], i[2]) if i else None for i in iss],
                 lambda v: "fill=white" if v[1] else HELD, lambda v: v[0]))
    rows.append(("opcode", "bus", [(i[1], i[2]) if i else None for i in iss],
                 lambda v: "fill=white" if v[1] else HELD, lambda v: v[0]))
    rows.append(None)
    for k in range(NSLOT):
        rows.append(("slot[%d]" % k, "slot", k, None, None))
    rows.append(None)
    rows.append(("l1.req", "bus", [T.l1_req(c) for c in cyc],
                 lambda v: "fill=cwrite" if v[1] else "fill=cread", lambda v: v[0]))
    rows.append(("l1.tag", "bus", [T.l1_result(c) for c in cyc],
                 lambda v: {"miss": "fill=cmiss", "join": "fill=cjoin", "hit": "fill=chit"}[v], None))
    rows.append(("axi.ar", "bus", [__import__("launch_trace").line_name(T.ar[c][1]) if c in T.ar else None
                                   for c in cyc], lambda v: "fill=cread", None))
    rows.append(("axi.r", "bus", [T.r_name.get(c) for c in cyc], lambda v: "fill=cread", None))
    rows.append(("axi.aw", "bus", [__import__("launch_trace").line_name(T.aw[c][1]) if c in T.aw else None
                                   for c in cyc], lambda v: "fill=cwrite", None))
    rows.append(("axi.w", "bus", [T.w_name.get(c) for c in cyc], lambda v: "fill=cwrite", None))
    rows.append(("axi.b", "bus", [T.b_name.get(c) for c in cyc], lambda v: "fill=cwrite", None))
    rows.append(None)
    rows.append(("rf.wr", "bus", [T.rf.get(c) for c in cyc],
                 lambda v: "fill=cld" if v[1] == "ld" else "fill=cfpu", lambda v: v[0]))

    nrow = sum(1 for r in rows if r) + 0.45 * sum(1 for r in rows if r is None)
    ybot = ytop - 0.32 - nrow * PITCH
    # cycle numbers and a light grid
    for c in cyc:
        o.append(r"\node[font=\fv, text=black!60] at (%s,%s) {%d};" % (f(ax.x(c) + CW / 2), f(ytop - 0.14), c))
    for c in range(c0, c1 + 2):
        o.append(r"\draw[gridline] (%s,%s) -- (%s,%s);" % (f(ax.x(c)), f(ytop - 0.26), f(ax.x(c)), f(ybot + 0.03)))
    o.append(r"\node[anchor=east, font=\fv, text=black!60] at (%s,%s) {cycle};" % (f(X0 - 0.10), f(ytop - 0.14)))
    y = ytop - 0.32
    for r in rows:
        if r is None:                            # a gap between signal groups
            y -= 0.45 * PITCH
            o.append(r"\draw[sep] (%s,%s) -- (%s,%s);" % (f(0.05), f(y + 0.2 * PITCH), f(ax.x_end), f(y + 0.2 * PITCH)))
            continue
        name, kind, vals, fills, text = r
        y -= PITCH
        ys = y + (PITCH - H) / 2
        label(o, ax, ys, H, name.replace("_", r"\_"))
        if kind == "clock":
            clock(o, ax, ys, H)
        elif kind == "bus":                      # one event per cycle: a transition every cycle
            bus(o, ax, ys, H, vals, fills=fills, text=text, font=r"\fv", min_w=0.3,
                split=lambda c: True)
        elif kind == "slot":
            slot_row(o, ax, ys, T, vals)
    o.append(r"\node[subcap, anchor=north west] at (%s,%s) {%s};" % (f(0.05), f(ybot - 0.02), title))
    return ybot - 0.40


def slot_row(o, ax, y, T, k):
    """A warp slot: one bus value per warp, shaded by its state in every cycle."""
    s = min(SLOPE, ax.cw * 0.2)
    warps = [T.warp_in(k, c) if T.state(k, c) else None for c in range(ax.c0, ax.c1 + 1)]
    fill = {"sleep": "csleep", "park": "cpark"}
    for i, c in enumerate(range(ax.c0, ax.c1 + 1)):
        st = T.state(k, c)
        if warps[i] is None or st not in fill:
            continue
        first = i == 0 or warps[i - 1] != warps[i]
        last = i == len(warps) - 1 or warps[i + 1] != warps[i]
        xa = ax.x(c) + (s if first and c != ax.c0 else 0)
        xb = ax.x(c + 1) - (s if last and c != ax.c1 else 0)
        o.append(r"\fill[%s] (%s,%s) rectangle (%s,%s);" % (fill[st], f(xa), f(y), f(xb), f(y + H)))
    bus(o, ax, y, H, warps, fills=lambda v: "fill=none", text=lambda v: "w%d" % v, font=r"\fv", min_w=0.3)


def legend(o, y):
    rows = [[("fill=white", "slot: warp running"), ("fill=csleep", "asleep on the register scoreboard"),
             ("fill=cpark", "parked until memory answers its store"), (HELD, "instruction held back")],
            [("fill=cread", "read"), ("fill=cwrite", "write"), ("fill=cmiss", "L1 miss"),
             ("fill=cjoin", "joins a miss in flight"), ("fill=chit", "L1 hit"),
             ("fill=cld", "register written by a load"), ("fill=cfpu", "by the FPU")]]
    for k, items in enumerate(rows):
        x, yy = 0.05, y - 0.30 * k
        for st, text in items:
            o.append(r"\draw[wire, %s] (%s,%s) rectangle (%s,%s);" % (st, f(x), f(yy - 0.07), f(x + 0.30), f(yy + 0.07)))
            o.append(r"\node[note, anchor=west] at (%s,%s) {%s};" % (f(x + 0.35), f(yy), text))
            x += 0.62 + 0.100 * len(text)


def main():
    T = Launch()
    o = [PRE]
    y = 0.0
    for c0, c1, title in WINDOWS:
        y = window(o, T, c0, c1, y, title)
    legend(o, y - 0.12)
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
