#!/usr/bin/env python3
"""gen_mem_fig.py - memory-level parallelism figure for the TVLSI paper.

(a) The coalescer on one warp's gather: eight lane addresses fall in four lines, and the
    coalescer sends one line request per cycle for the lowest pending lane together with
    every pending lane on the same line (rtl/accel/mem_engine.sv).
(b) The same eight loads on CVA6, Ara and SIMTiX over time. The limits are the machines'
    own (verified in the RTL):
      CVA6    write-through D-cache with one read MSHR: one miss in flight
              (cva6/core/cache_subsystem/wt_dcache_missunit.sv)
      Ara     indexed and strided accesses: one single-beat AXI request per element, at most
              VaddrgenInsnQueueDepth = 4 in flight (ara_pkg.sv, vlsu/addrgen.sv)
      SIMTiX  one request per distinct line, 16 tags / 16 MSHRs; the other warps keep
              issuing behind the register scoreboard.
Writes simtix_mem.tex; build with pdflatex.  Usage: python gen_mem_fig.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_mem.tex")

ADDR = [3, 17, 5, 40, 18, 7, 41, 90]          # word index of each lane's load
LINE = [a // 8 for a in ADDR]                  # 8 words (32 bytes) per line
ORDER = []                                     # lines in coalescer order (lowest pending lane)
for ln in LINE:
    if ln not in ORDER:
        ORDER.append(ln)
TINT = ["cA", "cB", "cC", "cD"]                # one tint per line, in coalescer order

PA = (-0.10, 6.55)                             # panel (a) x extent
PB = (6.75, 18.15)                             # panel (b) x extent
PY = (-0.05, 4.30)                             # panels' y extent

PRE = r"""% generated by gen_mem_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,patterns}
\definecolor{cctrl}{HTML}{D6E0EC}
\definecolor{cctrlb}{HTML}{3B5675}
\definecolor{cmem}{HTML}{FBE5D6}
\definecolor{cmemb}{HTML}{C55A11}
\definecolor{cA}{HTML}{CFE2F3}
\definecolor{cB}{HTML}{FCE5CD}
\definecolor{cC}{HTML}{D9EAD3}
\definecolor{cD}{HTML}{EAD1DC}
\newcommand{\fs}{\fontsize{6.4}{7.4}\selectfont}
\newcommand{\fss}{\fontsize{5.8}{6.6}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  base/.style={align=center, font=\fs, inner sep=1pt, line width=0.5pt},
  ctrl/.style={base, draw=cctrlb, fill=cctrl},
  tbl/.style={draw=black, line width=0.45pt},
  cell/.style={font=\fss, inner sep=0.5pt}, cellh/.style={font=\fss\bfseries, inner sep=0.5pt},
  panel/.style={draw=black!40, dashed, rounded corners=3pt, fill=black!1, line width=0.5pt},
  lbl/.style={font=\fs, inner sep=0.5pt},
  note/.style={font=\fss, inner sep=0.5pt, align=left},
  subcap/.style={font=\fs, inner sep=1pt},
  bar/.style={draw=cmemb, fill=cmem, line width=0.45pt},
  arr/.style={-{Latex[length=1.4mm, width=1.0mm]}, line width=0.55pt}]
"""


def f(x):
    return "%.3f" % x


def panel_a(o):
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(PA[0]), f(PY[0]), f(PA[1]), f(PY[1])))
    cw, ch = 0.62, 0.34
    tx, ty = 1.05, 3.72                         # top row's lower edge
    for r, h in enumerate(["lane", "word", "line"]):
        o.append(r"\node[cellh, anchor=east] at (%s,%s) {%s};" % (f(tx - 0.08), f(ty - r * ch + ch / 2), h))
    for i in range(8):
        tint = TINT[ORDER.index(LINE[i])]
        for r, v in enumerate([i, ADDR[i], LINE[i]]):
            xa, ya = tx + i * cw, ty - r * ch
            o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);"
                     % ("white" if r == 0 else tint, f(xa), f(ya), f(xa + cw), f(ya + ch)))
            o.append(r"\node[cell] at (%s,%s) {%d};" % (f(xa + cw / 2), f(ya + ch / 2), v))
    o.append(r"\node[note, anchor=north west] at (%s,%s) {line $=\lfloor \text{word}/8\rfloor$: 32-byte lines of eight words};"
             % (f(tx - 0.02), f(ty - 2 * ch - 0.07)))
    # coalescer and its four requests
    cy = 2.30
    o.append(r"\node[ctrl, minimum width=6.30cm, minimum height=0.32cm] at (%s,%s) {\textbf{Coalescer}:\ \fss one line request per cycle, for the lowest pending lane};"
             % (f(3.225), f(cy)))
    bw, gap, top, bh = 1.47, 0.14, cy - 0.30, 0.76
    for k, ln in enumerate(ORDER):
        lanes = [i for i in range(8) if LINE[i] == ln]
        xa = 0.075 + k * (bw + gap)
        o.append(r"\draw[arr] (%s,%s) -- (%s,%s);" % (f(xa + bw / 2), f(cy - 0.16), f(xa + bw / 2), f(top)))
        o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (TINT[k], f(xa), f(top - bh), f(xa + bw), f(top)))
        o.append(r"\node[cell, align=center] at (%s,%s) {cycle %d\\line %d\\%s %s};"
                 % (f(xa + bw / 2), f(top - bh / 2), k + 1, ln, "lanes" if len(lanes) > 1 else "lane",
                    ", ".join(str(i) for i in lanes)))
    o.append(r"\node[note, anchor=north west, text width=6.35cm] at (%s,%s) {%s};" % (f(0.0), f(top - bh - 0.10),
             r"Four line requests serve the eight lanes: a gather costs one request per distinct line, "
             r"$g\le L$, and a unit-stride warp access $g=1$."))
    o.append(r"\node[subcap] at (%s,%s) {(a) One warp's gather through the coalescer};"
             % (f((PA[0] + PA[1]) / 2), f(PY[0] - 0.30)))


def panel_b(o):
    X0, LAM, U = 9.20, 1.85, 0.12             # time origin, latency length, one cycle
    o.append(r"\draw[panel] (%s,%s) rectangle (%s,%s);" % (f(PB[0]), f(PY[0]), f(PB[1]), f(PY[1])))
    rows = []
    t, cva, seen = 0.0, [], set()             # CVA6: misses one after another, hits 1 cycle
    for i in range(8):
        if LINE[i] in seen:
            t += U
        else:
            seen.add(LINE[i])
            cva.append((t, t + LAM))
            t += LAM
    rows.append(("CVA6", ["one miss in flight"], cva, t, r"$\approx 4\Lambda$"))
    ara, free = [], [0.0] * 4                  # Ara: one request per element, <= 4 in flight
    for i in range(8):
        s = max(min(free), i * U)
        free[free.index(min(free))] = s + LAM
        ara.append((s, s + LAM))
    rows.append(("Ara", ["one request per element,", r"$\le 4$ in flight"], ara, max(e for _, e in ara),
                 r"$\approx 2\Lambda$"))
    smx = [(k * U, k * U + LAM) for k in range(len(ORDER))]
    rows.append(("SIMTiX", ["one request per line,", r"$\le 16$ in flight"], smx, max(e for _, e in smx),
                 r"$\approx \Lambda$"))

    ytop, rh, bh = 3.98, 1.10, 0.10
    for r, (name, sub, bars, end, tot) in enumerate(rows):
        yb = ytop - r * rh
        o.append(r"\node[lbl, anchor=north east, align=right] at (%s,%s) {\textbf{%s}\\[-0.5pt]\fss %s};"
                 % (f(X0 - 0.15), f(yb + 0.06), name, r"\\".join(sub)))
        step = 0.0 if name == "CVA6" else min(0.13, 0.78 / len(bars))
        for k, (s, e) in enumerate(bars):
            y = yb - 0.05 - k * step - (0.20 if name == "CVA6" else 0.0)
            o.append(r"\draw[bar] (%s,%s) rectangle (%s,%s);" % (f(X0 + s), f(y - bh / 2), f(X0 + e), f(y + bh / 2)))
        o.append(r"\draw[densely dotted, line width=0.5pt] (%s,%s) -- (%s,%s);"
                 % (f(X0 + end), f(yb + 0.06), f(X0 + end), f(yb - 0.90)))
        o.append(r"\node[lbl, anchor=west] at (%s,%s) {%s};" % (f(X0 + end + 0.08), f(yb - 0.25), tot))
        if name == "SIMTiX":
            yh = yb - 0.62
            o.append(r"\draw[draw=cctrlb, pattern=north east lines, pattern color=cctrlb!55, line width=0.4pt] (%s,%s) rectangle (%s,%s);"
                     % (f(X0), f(yh - 0.08), f(X0 + end), f(yh + 0.08)))
            o.append(r"\node[note, anchor=west] at (%s,%s) {meanwhile the other warps keep issuing (register scoreboard)};"
                     % (f(X0 + end + 0.08), f(yh)))
    ya = 0.42                                  # time axis and the latency scale under it
    xe = X0 + 4 * LAM + 4 * U + 0.55
    o.append(r"\draw[arr] (%s,%s) -- (%s,%s);" % (f(X0), f(ya), f(xe), f(ya)))
    o.append(r"\node[note, anchor=north east] at (%s,%s) {time (not to scale)};" % (f(xe), f(ya - 0.07)))
    o.append(r"\draw[{Latex[length=1.1mm]}-{Latex[length=1.1mm]}, line width=0.45pt] (%s,%s) -- (%s,%s);"
             % (f(X0), f(ya - 0.20), f(X0 + LAM), f(ya - 0.20)))
    o.append(r"\node[note, anchor=west] at (%s,%s) {$\Lambda$: memory latency};" % (f(X0 + LAM + 0.08), f(ya - 0.20)))
    o.append(r"\node[subcap] at (%s,%s) {(b) The same eight loads, each machine at its own limit};"
             % (f((PB[0] + PB[1]) / 2), f(PY[0] - 0.30)))


def main():
    o = [PRE]
    panel_a(o)
    panel_b(o)
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
