#!/usr/bin/env python3
"""gen_mem_fig.py - memory-level parallelism figure for the TVLSI paper, one column wide, drawn as
timing diagrams in the style of the paper's waveform figures.

(a) The coalescer on one warp's gather: eight lane addresses fall in four lines, and the
    coalescer sends one line request per cycle for the lowest pending lane together with
    every pending lane on the same line (rtl/accel/mem_engine.sv): a table of the lanes' words
    and lines, and the clock, the line request and the lanes it serves, cycle by cycle.
(b) The same eight loads on CVA6, Ara and SIMTiX, one row per request in flight, each request
    a bus value from its issue to its data, on a time axis in units of the memory latency
    Lambda (schematic). The limits are the machines' own (verified in the RTL):
      CVA6    write-through D-cache with one read MSHR: one miss in flight
              (cva6/core/cache_subsystem/wt_dcache_missunit.sv); the lanes run in order, so
              lines 0, 2, 5 and 11 miss one after another and the other loads hit
      Ara     indexed and strided accesses: one single-beat AXI request per element, at most
              VaddrgenInsnQueueDepth = 4 in flight (ara_pkg.sv, vlsu/addrgen.sv)
      SIMTiX  one request per distinct line, 16 tags / 16 MSHRs; the other warps keep
              issuing behind the register scoreboard.
Writes simtix_mem.tex; build with pdflatex.  Usage: python gen_mem_fig.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "simtix_mem.tex")

ADDR = [3, 17, 5, 40, 18, 7, 41, 90]          # word index of each lane's load
LINE = [a // 8 for a in ADDR]                  # 8 words (32 bytes) per line
ORDER = []                                     # lines in coalescer order (lowest pending lane)
for ln in LINE:
    if ln not in ORDER:
        ORDER.append(ln)
TINT = {ln: t for ln, t in zip(ORDER, ["cA", "cB", "cC", "cD"])}
X0, XE = 1.30, 8.55                            # left and right edge of the drawing area
RH, H = 0.30, 0.20                             # row pitch, signal height

PRE = r"""% generated by gen_mem_fig.py -- do not edit by hand
\documentclass[10pt]{standalone}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{amsmath,amssymb}
\usepackage{tikz}
\usetikzlibrary{arrows.meta}
\definecolor{cA}{HTML}{CFE2F3}
\definecolor{cB}{HTML}{FCE5CD}
\definecolor{cC}{HTML}{D9EAD3}
\definecolor{cD}{HTML}{EAD1DC}
\definecolor{celem}{HTML}{F2F2F2}
\newcommand{\fs}{\fontsize{6.2}{7.2}\selectfont}
\newcommand{\fss}{\fontsize{5.6}{6.4}\selectfont}
\newcommand{\fv}{\fontsize{5.0}{5.6}\selectfont}
\begin{document}
\begin{tikzpicture}[x=1cm, y=1cm,
  wire/.style={draw=black, line width=0.4pt, line join=round},
  tbl/.style={draw=black!70, line width=0.35pt},
  gridline/.style={draw=black!22, line width=0.3pt, dashed},
  name/.style={font=\fss\ttfamily, anchor=east, inner sep=0.5pt},
  grp/.style={font=\fs\bfseries, anchor=west, inner sep=0.5pt},
  note/.style={font=\fss, inner sep=0.5pt},
  subcap/.style={font=\fs, inner sep=1pt},
  dim/.style={{Latex[length=1.1mm, width=0.8mm]}-{Latex[length=1.1mm, width=0.8mm]}, line width=0.4pt}]
"""


def f(v):
    return "%.3f" % v


def hexv(o, xa, xb, y, fill, text=None, font=r"\fv", s=0.05):
    s = min(s, (xb - xa) / 3)
    ym = y + H / 2
    o.append(r"\draw[wire, fill=%s] (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- cycle;"
             % (fill, f(xa), f(ym), f(xa + s), f(y + H), f(xb - s), f(y + H), f(xb), f(ym), f(xb - s), f(y), f(xa + s), f(y)))
    if text:
        o.append(r"\node[font=%s, inner sep=0pt] at (%s,%s) {%s};" % (font, f((xa + xb) / 2), f(ym), text))


def idle(o, xa, xb, y):
    o.append(r"\draw[wire] (%s,%s) -- (%s,%s);" % (f(xa), f(y + H / 2), f(xb), f(y + H / 2)))


def panel_a(o, ytop):
    """the lanes' words and lines, and the coalescer cycle by cycle"""
    cw = (XE - X0) / 8
    y = ytop
    for r, (head, vals) in enumerate([("lane", list(range(8))), ("word", ADDR), ("line", LINE)]):
        yy = y - (r + 1) * RH
        o.append(r"\node[name, font=\fss\bfseries] at (%s,%s) {%s};" % (f(X0 - 0.10), f(yy + RH / 2), head))
        for i, v in enumerate(vals):
            fill = "black!6" if r == 0 else TINT[LINE[i]]
            o.append(r"\draw[tbl, fill=%s] (%s,%s) rectangle (%s,%s);" % (fill, f(X0 + i * cw), f(yy), f(X0 + (i + 1) * cw), f(yy + RH)))
            o.append(r"\node[note] at (%s,%s) {%d};" % (f(X0 + (i + 0.5) * cw), f(yy + RH / 2), v))
    y -= 3 * RH + 0.20
    o.append(r"\node[note, anchor=west] at (%s,%s) {line $=\lfloor\text{word}/8\rfloor$: 32-byte lines of eight words; one colour per line};"
             % (f(X0), f(y + 0.06)))
    # the coalescer, cycle by cycle
    n = len(ORDER)
    cc = (XE - X0) / n
    y -= 0.30
    for k in range(n):
        o.append(r"\node[font=\fv, text=black!60] at (%s,%s) {%d};" % (f(X0 + (k + 0.5) * cc), f(y), k + 1))
    o.append(r"\node[name, font=\fv, text=black!60] at (%s,%s) {cycle};" % (f(X0 - 0.10), f(y)))
    for k in range(n + 1):
        o.append(r"\draw[draw=black!12, line width=0.25pt] (%s,%s) -- (%s,%s);" % (f(X0 + k * cc), f(y - 0.10), f(X0 + k * cc), f(y - 0.12 - 3 * RH)))
    rows = ["clk", "l1.req", "lanes"]
    for r, name in enumerate(rows):
        ys = y - 0.12 - (r + 1) * RH + (RH - H) / 2
        o.append(r"\node[name] at (%s,%s) {%s};" % (f(X0 - 0.10), f(ys + H / 2), name))
        if name == "clk":
            pts = []
            for k in range(n):
                xa, xm = X0 + k * cc, X0 + (k + 0.5) * cc
                pts += ["(%s,%s)" % (f(xa), f(ys)), "(%s,%s)" % (f(xa), f(ys + H)), "(%s,%s)" % (f(xm), f(ys + H)), "(%s,%s)" % (f(xm), f(ys))]
            pts.append("(%s,%s)" % (f(XE), f(ys)))
            o.append(r"\draw[wire] %s;" % " -- ".join(pts))
        for k, ln in enumerate(ORDER):
            xa, xb = X0 + k * cc, X0 + (k + 1) * cc
            lanes = [i for i in range(8) if LINE[i] == ln]
            if name == "l1.req":
                hexv(o, xa, xb, ys, TINT[ln], "line %d" % ln)
            elif name == "lanes":
                hexv(o, xa, xb, ys, "white", ", ".join(str(i) for i in lanes))
    y -= 0.12 + 3 * RH + 0.22
    o.append(r"\node[note, anchor=west, align=left] at (%s,%s) {Four line requests serve the eight lanes: a gather costs one request per\\distinct line, $g\le L$, and a unit-stride warp access $g=1$.};"
             % (f(X0 - 1.2), f(y - 0.10)))
    y -= 0.48
    o.append(r"\node[subcap] at (%s,%s) {(a) One warp's gather through the coalescer};" % (f((X0 - 1.2 + XE) / 2), f(y)))
    return y - 0.30


def panel_b(o, ytop):
    """the eight loads on each machine: one row per request in flight"""
    lam = (XE - 0.55 - X0) / 4.15                  # cm per Lambda
    d = 0.05 * lam                                  # one cycle, drawn schematically
    X = lambda t: X0 + t * lam
    c = d / lam                                     # one cycle in units of Lambda
    vline = lambda ln: {0: 0, 2: 1, 5: 2, 11: 5}[ln]   # the same lanes' 64-byte Vortex line
    groups = [
        ("CVA6", "one miss in flight", ["miss"],
         [[("line %d" % ln, k, k + 1, TINT[ln]) for k, ln in enumerate(ORDER)]], 4, 0),
        ("Ara", r"one request per element, $\le 4$ in flight", ["req %d" % s for s in range(4)],
         [[("e%d" % s, s * c, 1 + s * c, "celem"), ("e%d" % (s + 4), 1 + s * c, 2 + s * c, "celem")]
          for s in range(4)], 2, 3),
        # FGPU: 128-byte lines, so the eight loads touch lines 0 (lanes 0, 1, 2, 4, 5), 1 (3, 6)
        # and 2 (7); two line fills in flight (gmem_cntrl_tag: N_WR_FIFOS = 2)
        ("FGPU", r"two line fills in flight; 128-byte lines", ["fill 0", "fill 1"],
         [[("line 0", 0, 1, "celem"), ("line 2", 1, 2, "celem")], [("line 1", c, 1 + c, "celem")]], 2, 0),
        # Vortex: the LSU coalescer merges lanes per 16-byte block in two groups of four lanes,
        # two cache requests per cycle; the 64-byte-line D-cache starts one fill per new line
        # (16 MSHRs) and merges the rest into it: lines 0 and 1 in cycle 1, 2 in 3, 5 in 4
        ("Vortex", r"16 MSHRs; 64-byte lines", ["fill %d" % k for k in range(4)],
         [[("line %d" % vline(ln), t * c, 1 + t * c, TINT[ln])] for ln, t in zip(ORDER, (0, 0, 2, 3))], 1, 3),
        ("SIMTiX", r"one request per line, $\le 16$ in flight", ["req %d" % k for k in range(4)],
         [[("line %d" % ln, k * c, 1 + k * c, TINT[ln])] for k, ln in enumerate(ORDER)], 1, 3),
    ]
    y = ytop
    for gname, gnote, labels, rows, total, extra in groups:
        o.append(r"\node[grp] at (%s,%s) {%s};" % (f(X0 - 1.2), f(y - 0.13), gname))
        o.append(r"\node[note, anchor=west, text=black!70] at (%s,%s) {%s};" % (f(X0 - 1.2 + 0.11 * len(gname) + 0.25), f(y - 0.13), gnote))
        y -= 0.28
        for label, segs in zip(labels, rows):
            y -= RH
            ys = y + (RH - H) / 2
            o.append(r"\node[name] at (%s,%s) {%s};" % (f(X0 - 0.10), f(ys + H / 2), label))
            t = 0.0
            for text, ta, tb, fill in segs:
                if ta > t:
                    idle(o, X(t), X(ta), ys)
                hexv(o, X(ta), X(tb), ys, fill, text)
                t = tb
            idle(o, X(t), X(4.15), ys)
        # the time this machine needs for the eight loads
        tend = total + extra * c
        o.append(r"\draw[line width=0.5pt] (%s,%s) -- (%s,%s);" % (f(X(tend)), f(y + 0.02), f(X(tend)), f(y + len(rows) * RH + 0.02)))
        o.append(r"\node[note, anchor=west, font=\fs, fill=white, inner sep=0.8pt] at (%s,%s) {$\approx %s\Lambda$};"
                 % (f(X(tend) + 0.04), f(y + (len(rows) * RH) / 2), "" if total == 1 else str(total)))
        y -= 0.16
    # time axis in units of Lambda, with a dashed grid
    ya = y - 0.02
    for k in range(5):
        o.append(r"\draw[gridline] (%s,%s) -- (%s,%s);" % (f(X(k)), f(ya), f(X(k)), f(ytop - 0.30)))
        o.append(r"\node[note] at (%s,%s) {%s};" % (f(X(k)), f(ya - 0.14), "0" if k == 0 else (r"$\Lambda$" if k == 1 else r"$%d\Lambda$" % k)))
    o.append(r"\draw[-{Latex[length=1.2mm, width=0.9mm]}, line width=0.4pt] (%s,%s) -- (%s,%s);" % (f(X(0)), f(ya), f(X(4.15)), f(ya)))
    o.append(r"\node[note, anchor=east] at (%s,%s) {time};" % (f(X0 - 0.10), f(ya - 0.14)))
    o.append(r"\node[note, anchor=west, text=black!60] at (%s,%s) {$\Lambda$: latency of one memory request; a cycle is drawn short};" % (f(X(1.6)), f(ya - 0.40)))
    o.append(r"\node[subcap] at (%s,%s) {(b) The same eight loads, each machine at its own limit};" % (f((X0 - 1.2 + XE) / 2), f(ya - 0.75)))


def main():
    o = [PRE]
    y = panel_a(o, 0.0)
    panel_b(o, y)
    o.append(r"\end{tikzpicture}")
    o.append(r"\end{document}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
