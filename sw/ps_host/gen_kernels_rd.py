"""gen_kernels_rd.py -- turn kernels/rodinia/*.hex into kernels_rd.h for the board host.

    python sw/ps_host/gen_kernels_rd.py

The Rodinia suite (docs/rodinia_plan.md) loads suite 2's kernels (kernels_s2.h) and,
after them, its own: they are packed in 64-byte slots from the end of suite 2's (as
sim/gen_rodinia.place_kernels does), PC_RD_<NAME> gives each one's offset, and
rd_load_all() in rodinia.inc writes them.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
KDIR_S2 = os.path.join(HERE, '..', '..', 'kernels', 'suite2')
KDIR = os.path.join(HERE, '..', '..', 'kernels', 'rodinia')
S2_KERNELS = ['pathfinder', 'hotspot', 'jacobi2d', 'mv_row', 'mv_col', 'pr_contrib', 'pr_pull', 'cc_step',
              'bp_forward', 'bp_adjust', 'rs_hist', 'rs_scan', 'rs_scatter', 'blackscholes']
KERNELS = ['bfs', 'hotspot_rd', 'nn', 'hotspot3d', 'gauss_fan1', 'gauss_fan2', 'kmeans_rd']
IRAM_WORDS = 1024

pc = 0
for k in S2_KERNELS:
    pc += 64 * -(-len(open(os.path.join(KDIR_S2, k + '.hex')).read().split()) // 16)
base = pc
out = ['/* kernels_rd.h - generated by gen_kernels_rd.py from the kernels/rodinia .hex files; do not edit */',
       '#include <stdint.h>', '']
for k in KERNELS:
    words = open(os.path.join(KDIR, k + '.hex')).read().split()
    out.append(f'#define PC_RD_{k.upper()} 0x{pc:03X}u')
    out.append(f'static const uint32_t krd_{k}[{len(words)}] = {{')
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x' + w for w in words[i:i + 8]) + ',')
    out.append('};')
    pc += 64 * -(-len(words) // 16)
assert pc <= 4 * IRAM_WORDS, f'suite 2 and Rodinia kernels need {pc} bytes'
out += ['', 'struct rd_kernel { uint32_t pc; const uint32_t *w; unsigned n; };',
        'static const struct rd_kernel rd_kernels[] = {']
out += [f'    {{ PC_RD_{k.upper()}, krd_{k}, sizeof krd_{k} / 4u }},' for k in KERNELS]
out += ['};', '']
open(os.path.join(HERE, 'kernels_rd.h'), 'w', newline='\n').write('\n'.join(out))
print(f'kernels_rd.h: {len(KERNELS)} kernels from byte {base}, {pc} of {4 * IRAM_WORDS} instruction-RAM bytes')
