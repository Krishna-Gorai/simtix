"""gen_kernels_s2.py -- turn kernels/suite2/*.hex into kernels_s2.h for the board host.

    python sw/ps_host/gen_kernels_s2.py

Suite 2 (docs/suite2_plan.md) runs after suite 1 and its power pass, so its kernels
take the whole instruction RAM: they are packed from byte 0 in 64-byte slots (as
sim/gen_apps.place_kernels does), PC_S2_<NAME> gives each one's offset, and
s2_load_all() in apps.c writes them.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
KDIR = os.path.join(HERE, '..', '..', 'kernels', 'suite2')
KERNELS = ['pathfinder', 'hotspot', 'jacobi2d', 'mv_row', 'mv_col', 'pr_contrib', 'pr_pull', 'cc_step',
           'bp_forward', 'bp_adjust', 'rs_hist', 'rs_scan', 'rs_scatter', 'blackscholes']
IRAM_WORDS = 1024

out = ['/* kernels_s2.h - generated by gen_kernels_s2.py from the kernels/suite2 .hex files; do not edit */',
       '#include <stdint.h>', '']
pc = 0
for k in KERNELS:
    words = open(os.path.join(KDIR, k + '.hex')).read().split()
    out.append(f'#define PC_S2_{k.upper()} 0x{pc:03X}u')
    out.append(f'static const uint32_t k2_{k}[{len(words)}] = {{')
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x' + w for w in words[i:i + 8]) + ',')
    out.append('};')
    pc += 64 * -(-len(words) // 16)
assert pc <= 4 * IRAM_WORDS, f'suite 2 kernels need {pc} bytes'
out += ['', 'struct s2_kernel { uint32_t pc; const uint32_t *w; unsigned n; };',
        'static const struct s2_kernel s2_kernels[] = {']
out += [f'    {{ PC_S2_{k.upper()}, k2_{k}, sizeof k2_{k} / 4u }},' for k in KERNELS]
out += ['};', '']
open(os.path.join(HERE, 'kernels_s2.h'), 'w', newline='\n').write('\n'.join(out))
print(f'kernels_s2.h: {len(KERNELS)} kernels, {pc} of {4 * IRAM_WORDS} instruction-RAM bytes')
