"""gen_kernels_rv.py -- the SIMTiX kernels of RiVEC batch 1 as kernels_rv.h for the board host.

    python sw/ps_host/gen_kernels_rv.py

RiVEC runs alone (hosts built with `rivec`, define RV_ONLY): its kernels replace the
others in the instruction RAM, packed in 64-byte slots from byte 0 in the order of
sim/gen_rivec.py's place_kernels (kernels/apps gemm, gemm_rb, spmv, spmv_z; suite 2's
pathfinder; kernels/rivec). PC_RV_<NAME> gives each one's offset and rv_load_all() in
rivec.inc writes them.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import genopts                                    # --kroot DIR --out DIR (other lane counts)
K, OUT = genopts.parse()
KERNELS = [('apps', 'gemm'), ('apps', 'gemm_rb'), ('apps', 'spmv'), ('apps', 'spmv_z'),
           ('suite2', 'pathfinder'),
           ('rivec', 'axpy_rv'), ('rivec', 'jacobi_rv'), ('rivec', 'bs_rv'), ('rivec', 'lavamd_rv')]
IRAM_WORDS = 1024

pc = 0
out = ['/* kernels_rv.h - generated by gen_kernels_rv.py from kernels/{apps,suite2,rivec} .hex files; do not edit */',
       '#include <stdint.h>', '']
for d, k in KERNELS:
    words = open(os.path.join(K, d, k + '.hex')).read().split()
    out.append(f'#define PC_RV_{k.upper()} 0x{pc:03X}u')
    out.append(f'static const uint32_t krv_{k}[{len(words)}] = {{')
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x' + w for w in words[i:i + 8]) + ',')
    out.append('};')
    pc += 64 * -(-len(words) // 16)
assert pc <= 4 * IRAM_WORDS, f'RiVEC kernels need {pc} bytes'
out += ['', 'struct rv_kernel { uint32_t pc; const uint32_t *w; unsigned n; };',
        'static const struct rv_kernel rv_kernels[] = {']
out += [f'    {{ PC_RV_{k.upper()}, krv_{k}, sizeof krv_{k} / 4u }},' for _, k in KERNELS]
out += ['};', '']
open(os.path.join(OUT, 'kernels_rv.h'), 'w', newline='\n').write('\n'.join(out))
print(f'kernels_rv.h: {len(KERNELS)} kernels, {pc} of {4 * IRAM_WORDS} instruction-RAM bytes')
