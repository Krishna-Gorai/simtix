"""
gen_kernels.py -- emit kernels.h (C arrays of kernel words) for the ARM host.

    python sw/ps_host/gen_kernels.py

Reads kernels/sync/<name>.svh (the committed kernel images, `mem[at+k] =
32'h...;` lines written by kernels/sync/build.py) and writes sw/ps_host/kernels.h.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SYNC = os.path.join(HERE, '..', '..', 'kernels', 'sync')
KERNELS = ['reduce_shfl', 'histogram', 'reduce_all', 'hist_shared']

with open(os.path.join(HERE, 'kernels.h'), 'w', newline='\n') as out:
    out.write('/* Generated by gen_kernels.py from kernels/sync/*.svh -- do not edit. */\n')
    out.write('#ifndef KERNELS_H\n#define KERNELS_H\n#include <stdint.h>\n\n')
    for k in KERNELS:
        text = open(os.path.join(SYNC, k + '.svh')).read()
        words = re.findall(r"32'h([0-9a-fA-F]{8})", text)
        out.write(f'static const uint32_t k_{k}[{len(words)}] = {{\n')
        for i in range(0, len(words), 6):
            out.write('    ' + ', '.join('0x' + w for w in words[i:i + 6]) + ',\n')
        out.write('};\n\n')
    out.write('#endif\n')
print('wrote kernels.h:', ', '.join(KERNELS))
