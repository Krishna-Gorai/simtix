"""
gen_kernels.py -- emit kernels.h (C arrays of kernel words) for the ARM host.

    python sw/ps_host/gen_kernels.py

Reads the committed kernel images, kernels/sync/<name>.svh (`mem[at+k] =
32'h...;` lines written by kernels/sync/build.py) and kernels/apps/<name>.hex
(one word per line, written by kernels/apps/build.py), and writes
sw/ps_host/kernels.h.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
KDIR = os.path.join(HERE, '..', '..', 'kernels')
SYNC = ['reduce_shfl', 'histogram', 'reduce_all', 'hist_shared']
APPS = ['gemm', 'spmv', 'stencil', 'kmeans', 'bfs', 'scan', 'scan_add', 'mlp']


def words_of(name):
    if name in SYNC:
        return re.findall(r"32'h([0-9a-fA-F]{8})", open(os.path.join(KDIR, 'sync', name + '.svh')).read())
    return open(os.path.join(KDIR, 'apps', name + '.hex')).read().split()


with open(os.path.join(HERE, 'kernels.h'), 'w', newline='\n') as out:
    out.write('/* Generated by gen_kernels.py from the kernels/sync .svh and kernels/apps .hex'
              ' files -- do not edit. */\n')
    out.write('#ifndef KERNELS_H\n#define KERNELS_H\n#include <stdint.h>\n\n')
    for k in SYNC + APPS:
        words = words_of(k)
        out.write(f'static const uint32_t k_{k}[{len(words)}] = {{\n')
        for i in range(0, len(words), 6):
            out.write('    ' + ', '.join('0x' + w for w in words[i:i + 6]) + ',\n')
        out.write('};\n\n')
    out.write('#endif\n')
print('wrote kernels.h:', ', '.join(SYNC + APPS))
