"""compare_board_l16.py - every benchmark row of the 16-lane board run against the 8-lane board run
and the A53, from the board logs (docs/lanes16_board_results.md).

    python sim/compare_board_l16.py          -> docs/lanes16_board_results.csv + a markdown table

16 lanes: docs/zcu102_board_run_l16_{main,rodinia,rivec}.txt (100 MHz). 8 lanes (v3 board design,
115.37 MHz): docs/zcu102_board_run_v3_s2.txt (sync kernels, applications, suite 2),
rodinia_results.csv, rivec_results.csv. A53 times are each run's own -O2 measurement.
"""
import csv
import math
import os

DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs')
SYNC = {'reduce_shfl', 'histogram', 'hist_shared', 'amo_contend'}
APPS = {'gemm', 'spmv', 'stencil', 'kmeans', 'bfs', 'scan', 'mlp', 'gemmrb', 'scanseg', 'stencilrb',
        'kmeansu', 'spmvz', 'conv8', 'embag', 'hashj', 'mandel', 'swat'}


def board(name, start=None):
    """BOARD rows (kernel, N, cycles, accel_us, a53_us), from the line `start` on if given."""
    rows, on = [], start is None
    for line in open(os.path.join(DOCS, name), encoding='utf-8', errors='replace'):
        line = line.replace('\x00', '').strip()
        if start and line.startswith(start):
            on = True
        if on and line.startswith('BOARD,') and not line.startswith('BOARD,kernel'):
            f = line.split(',')
            rows.append((f[1], int(f[2]), int(f[3]), float(f[4]), float(f[5])))
    return rows


def results_csv(name):
    out = {}
    for x in csv.DictReader(open(os.path.join(DOCS, name))):
        out.setdefault((x['app'], int(x['size'])),
                       (float(x['simtix_cycles']), float(x['simtix_us']), float(x['a53_O2_us'])))
    return out


def main():
    rows = []
    b8 = {(k, n): (c, us, a) for k, n, c, us, a in board('zcu102_board_run_v3_s2.txt')}
    for k, n, c, us, a in board('zcu102_board_run_l16_main.txt'):
        if (k, n) in b8:
            suite = 'sync' if k in SYNC else 'apps' if k in APPS else 'suite2'
            rows.append((suite, k, n) + b8[(k, n)] + (c, us, a))
    for suite, log, start, ref in (('rodinia', 'zcu102_board_run_l16_rodinia.txt', 'RODINIA,suite,start', 'rodinia_results.csv'),
                                   ('rivec', 'zcu102_board_run_l16_rivec.txt', 'RIVEC,suite,start', 'rivec_results.csv')):
        r8 = results_csv(ref)
        for k, n, c, us, a in board(log, start):
            if (k, n) in r8:
                rows.append((suite, k, n) + r8[(k, n)] + (c, us, a))
    out = os.path.join(DOCS, 'lanes16_board_results.csv')
    with open(out, 'w', newline='\n') as f:
        f.write('suite,kernel,N,cycles_8L,us_8L_115MHz,a53_us_8Lrun,cycles_16L,us_16L_100MHz,a53_us_16Lrun,'
                'speedup_16L_vs_8L_time,cycle_ratio_8L_over_16L,speedup_8L_vs_A53,speedup_16L_vs_A53\n')
        for s, k, n, c8, us8, a8, c16, us16, a16 in rows:
            f.write(f'{s},{k},{n},{c8:.0f},{us8:.1f},{a8:.1f},{c16},{us16:.1f},{a16:.1f},'
                    f'{us8 / us16:.3f},{c8 / c16:.3f},{a8 / us8:.3f},{a16 / us16:.3f}\n')
    names = {'sync': 'Sync kernels', 'apps': 'Applications', 'suite2': 'Suite 2', 'rodinia': 'Rodinia', 'rivec': 'RiVEC'}
    fmt = lambda us: f'{us:,.1f}' if us < 10000 else f'{us / 1000:,.1f} ms'
    print('| # | Kernel | N | A53 | 8 lanes @115 MHz | 16 lanes @100 MHz | **16L vs 8L** | cycles 8L/16L | 8L vs A53 | 16L vs A53 |')
    print('|---|---|---|---|---|---|---|---|---|---|')
    cur, i = None, 0
    for s, k, n, c8, us8, a8, c16, us16, a16 in rows:
        if s != cur:
            print(f'| | **{names[s]}** | | | | | | | | |')
            cur = s
        i += 1
        sp = us8 / us16
        mark = '' if sp >= 1 else ' (slower)'
        print(f'| {i} | {k} | {n:,} | {fmt(a16)} | {fmt(us8)} | {fmt(us16)} | **{sp:.2f}×**{mark} | {c8 / c16:.2f} | '
              f'{a8 / us8:.2f}× | {a16 / us16:.2f}× |')
    g = lambda v: math.exp(sum(map(math.log, v)) / len(v))
    print(f'\n{len(rows)} rows; geomean 16L vs 8L {g([r[4] / r[7] for r in rows]):.3f}x; written {out}')
    write_markdown(rows, names, fmt)
    write_latex(rows, g)


def write_markdown(rows, names, fmt):
    """docs/lanes16_board_table.md: the full per-benchmark table (same as printed)."""
    p = os.path.join(DOCS, 'lanes16_board_table.md')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# 16-lane SIMTiX on the ZCU102: every benchmark (generated by sim/compare_board_l16.py)\n\n'
                'Measured on the board, 2026-11-17. Times in microseconds unless marked ms. 16L vs 8L = 8-lane '
                'time / 16-lane time (includes the 100 vs 115.37 MHz clock); cycles 8L/16L removes the clock. '
                'A53 = Cortex-A53 at 1.2 GHz, -O2, timed in each run (column: the 16-lane run; 8L vs A53 uses '
                'the 8-lane run\'s own A53 time). All 82 rows pass bit-exact.\n\n')
        f.write('| # | Kernel | N | A53 | 8 lanes @115 MHz | 16 lanes @100 MHz | **16L vs 8L** | cycles 8L/16L | 8L vs A53 | 16L vs A53 |\n')
        f.write('|---|---|---|---|---|---|---|---|---|---|\n')
        cur, i = None, 0
        for s, k, n, c8, us8, a8, c16, us16, a16 in rows:
            if s != cur:
                f.write(f'| | **{names[s]}** | | | | | | | | |\n')
                cur = s
            i += 1
            sp = us8 / us16
            f.write(f'| {i} | {k} | {n:,} | {fmt(a16)} | {fmt(us8)} | {fmt(us16)} | **{sp:.2f}×**'
                    f'{"" if sp >= 1 else " (slower)"} | {c8 / c16:.2f} | {a8 / us8:.2f}× | {a16 / us16:.2f}× |\n')
    print('written', p)


# display names and input descriptions for the paper tables
DISP = {
    'reduce_shfl': 'Reduce (shuffle)', 'histogram': 'Histogram (AMO)', 'hist_shared': 'Histogram (shared)',
    'amo_contend': 'AMO contention', 'gemm': 'GEMM', 'spmv': 'SpMV', 'stencil': 'Stencil', 'kmeans': 'k-means',
    'bfs': 'BFS', 'scan': 'Scan', 'mlp': 'MLP, INT8', 'gemmrb': 'GEMM-RB', 'scanseg': 'Segmented scan',
    'stencilrb': 'Stencil-RB', 'kmeansu': 'k-means-U', 'spmvz': 'SpMV-Z', 'conv8': 'CNN, INT8',
    'embag': 'Embedding bag', 'hashj': 'Hash join', 'mandel': 'Mandelbrot', 'swat': 'Smith-Waterman',
    'pathfinder': 'Pathfinder', 'hotspot': 'Hotspot', 'jacobi2d': 'Jacobi-2D', 'atax': 'ATAX', 'bicg': 'BiCG',
    'pagerank': 'PageRank', 'cc': 'Connected comp.', 'backprop': 'Backprop', 'sort': 'Radix sort',
    'blackscholes': 'Black-Scholes', 'nn': 'NN', 'hotspot3d': 'Hotspot3D', 'gaussian': 'Gaussian',
    'axpy': 'AXPY', 'matmul': 'Matmul', 'jacobi': 'Jacobi-2D', 'lavamd': 'LavaMD'}
SUITE_TEX = {'sync': 'Synchronization kernels', 'apps': 'Applications', 'suite2': 'Suite 2',
             'rodinia': 'Rodinia', 'rivec': 'RiVEC'}


def ms(us):
    v = us / 1000.0
    return f'{v:.3f}' if v < 1 else f'{v:.2f}' if v < 100 else f'{v:,.0f}'.replace(',', '{,}')


def write_latex(rows, g):
    """docs/paper/tab_lanes16_board.tex (summary per suite, for the paper) and
    docs/paper/supp_lanes16_board.tex (every row, two tables, for the supplement)."""
    paper = os.path.join(DOCS, 'paper')
    # no table notes (authors' rule, 2026-11-23): the paper's and the supplement's text say what
    # the columns mean
    with open(os.path.join(paper, 'tab_lanes16_board.tex'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('% generated by sim/compare_board_l16.py from the board logs (2026-11-17); \\input where needed\n')
        # the paper's table style (2026-11-28): booktabs, heads bottom-aligned, one quantity per
        # cell, no units or symbols in the cells
        f.write('\\begin{table}[t]\n\\caption{Sixteen Lanes Against Eight Lanes and the Cortex-A53}\n'
                '\\label{tab:lanes16_board}\n\\centering\\footnotesize\n\\setlength{\\tabcolsep}{3.2pt}\n'
                '\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n'
                ' & \\multicolumn{2}{c}{16 vs.\\ 8 lanes} & \\multicolumn{4}{c}{SIMTiX vs.\\ Cortex-A53}\\\\\n'
                '\\cmidrule(lr){2-3}\\cmidrule(lr){4-7}\n'
                ' & & & \\multicolumn{2}{c}{Speedup} & \\multicolumn{2}{c}{Faster}\\\\\n'
                '\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\n'
                'Suite (runs) & Speedup & Faster & $L=8$ & $L=16$ & $L=8$ & $L=16$\\\\\n\\midrule\n')
        for s in ('sync', 'apps', 'suite2', 'rodinia', 'rivec', None):
            v = [r for r in rows if s is None or r[0] == s]
            name = 'All' if s is None else {'sync': 'Synchronization', 'suite2': 'Second suite'}.get(s, SUITE_TEX[s])
            if s is None:
                f.write('\\midrule\n')
            sp = [r[4] / r[7] for r in v]
            n = len(v)
            f.write(f'{name} ({n}) & {g(sp):.2f} & {sum(x > 1 for x in sp)}/{n} & '
                    f'{g([r[5] / r[4] for r in v]):.2f} & {g([r[8] / r[7] for r in v]):.2f} & '
                    f'{sum(r[5] / r[4] > 1 for r in v)}/{n} & {sum(r[8] / r[7] > 1 for r in v)}/{n}\\\\\n')
        f.write('\\bottomrule\n\\end{tabular}\n\\end{table}\n')
    parts = (('sync', 'apps'), ('suite2', 'rodinia', 'rivec'))
    with open(os.path.join(paper, 'supp_lanes16_board.tex'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('% generated by sim/compare_board_l16.py from the board logs (2026-11-17)\n')
        for pi, part in enumerate(parts):
            f.write('\\begin{table*}[p]\n')
            f.write('\\caption{Sixteen Lanes on the Board: '
                    + ('Synchronization Kernels and Applications' if pi == 0 else 'Suite 2, Rodinia and RiVEC')
                    + '}\n')
            f.write(f'\\label{{tab:lanes16_board_all{pi + 1}}}\n\\centering\\footnotesize\n\\setlength{{\\tabcolsep}}{{4pt}}\n'
                    '\\begin{tabular}{lrrrrrrrr}\n\\toprule\n'
                    'Kernel & Input & \\multicolumn{3}{c}{Time (ms)} & \\multicolumn{2}{c}{16L vs 8L} & '
                    '\\multicolumn{2}{c}{vs A53}\\\\\n'
                    '\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\n'
                    ' & & A53 & 8 lanes & 16 lanes & time & cycles & 8L & 16L\\\\\n')
            for s in part:
                f.write(f'\\midrule\n\\multicolumn{{9}}{{l}}{{\\textit{{{SUITE_TEX[s]}}}}}\\\\\n')
                for r in rows:
                    if r[0] != s:
                        continue
                    _, k, n, c8, us8, a8, c16, us16, a16 = r
                    sp = us8 / us16
                    spt = f'{sp:.2f}' if sp >= 1 else f'\\textit{{{sp:.2f}}}'
                    f.write(f'{DISP.get(k, k)} & {n:,}'.replace(',', '{,}') +
                            f' & {ms(a16)} & {ms(us8)} & {ms(us16)} & {spt} & {c8 / c16:.2f} & '
                            f'{a8 / us8:.2f} & {a16 / us16:.2f}\\\\\n')
            f.write('\\bottomrule\n\\end{tabular}\n\n\\end{table*}\n\n')
    print('written', os.path.join(paper, 'tab_lanes16_board.tex'), 'and supp_lanes16_board.tex')


if __name__ == '__main__':
    main()
